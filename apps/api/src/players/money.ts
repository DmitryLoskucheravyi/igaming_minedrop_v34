/* ============================================================
   ГРОШІ ГРАВЦЯ — два баланси, оборот, фріспіни.

   Модель узята з того, як це влаштовано в казино, і головне в ній —
   РОЗДІЛЕННЯ. Раніше в нас був один баланс і число «скільки з нього
   не виводиться»; виглядало простіше, але кожне питання про рух
   грошей («з чого зіграла ця ставка», «куди пішов цей виграш»)
   не мало відповіді. Тепер відповідь є завжди.

   cash    — гроші гравця. Виводяться будь-коли.
   bonus   — подаровані гроші й виграш із безкоштовних прокрутів.
             Грати ними можна одразу, виводити — лише після відіграшу.

   На екрані гравець бачить ОДНЕ число (cash + bonus): він грає всім
   разом, і ділити баланс у нього перед очима нема потреби. Розділення
   показує лише вікно виводу, де воно й справді щось означає.

   ---- ЗВІДКИ СПИСУЄТЬСЯ СТАВКА ----
   СПЕРШУ З БОНУСУ. Єдиного правила в індустрії немає (буває й cash
   first, і пропорційно), тож це наш вибір, і ось чому саме він:
   бонус — це те, що треба відіграти, і поки він лежить недоторканим,
   гравець не рухається до виводу взагалі. Списуючи його першим, ми
   даємо відіграшу йти; а якщо бонус програно — зобов'язання зникає
   разом із ним, і гравець не лишається з боргом за гроші, яких уже
   немає.

   ---- КУДИ ЙДЕ ВИГРАШ ----
   У ТІЙ САМІЙ ПРОПОРЦІЇ, в якій пішла ставка. Ставка на 100, з них
   40 з бонусу — виграш ділиться 40/60. Інакше з'явився б спосіб
   «відмити» бонус: поставив бонусом, забрав виграш готівкою.

   ---- ОБОРОТ ----
   wagerDone росте на суму КОЖНОЇ ставки (з поправкою на contribution),
   незалежно від того, виграла вона чи ні. Відіграш — це оборот, а не
   програш: баланс по дорозі стрибає вгору й вниз, вимога від цього не
   змінюється.
   ============================================================ */

/** Скільки ставки зараховується в оборот у різних режимах. */
export const CONTRIBUTION = {
  /* Звичайний прокрут і подарований — повністю. */
  bet: 1,
  /* Бонус бай. У казино feature buy часто взагалі виключають із
     відіграшу (він дає гарантований результат і нівелює дисперсію).
     Поки лишаємо 100%, але ручка тут, і це свідоме рішення, а не
     недогляд. */
  buy: 1,
} as const;

export interface MoneySplit {
  /** скільки взято з бонусу */
  fromBonus: number;
  /** скільки взято з готівки */
  fromCash: number;
}

/* Розкласти ставку між балансами: спершу бонус, решта — готівка.
   Не перевіряє, чи вистачає грошей: це робить той, хто кличе. */
export function splitStake(bonus: number, cash: number, amount: number): MoneySplit {
  const fromBonus = Math.min(Math.max(0, bonus), amount);
  return { fromBonus, fromCash: amount - fromBonus };
}

/* Поділити виплату в тій самій пропорції, що й ставка.

   Округлення навмисно на користь БОНУСУ: зайва копійка має піти туди,
   де вона ще мусить бути відіграна, а не в готівку. Інакше на довгій
   серії дрібних раундів бонус потроху перетікав би у виводимі гроші
   сам собою. */
export function splitPayout(stake: MoneySplit, payout: number): MoneySplit {
  const total = stake.fromBonus + stake.fromCash;
  if (payout <= 0) return { fromBonus: 0, fromCash: 0 };
  if (total <= 0 || stake.fromBonus <= 0) return { fromBonus: 0, fromCash: payout };
  if (stake.fromCash <= 0) return { fromBonus: payout, fromCash: 0 };
  const toBonus = Math.ceil((payout * stake.fromBonus) / total);
  return { fromBonus: toBonus, fromCash: payout - toBonus };
}
