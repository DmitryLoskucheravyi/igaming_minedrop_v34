/* ============================================================
   ПРАВИЛА БОНУСНИХ ГРОШЕЙ — в одному місці, бо вони стосуються і
   реферальних виплат, і будь-якого майбутнього подарунка.

   Три обмеження, і кожне закриває свою дірку:

   BONUS_MAX_BET_SHARE — стеля ставки, поки бонус не відіграний.
     Без неї відіграш не означає нічого: ціль у 2000 ₽ знімається ОДНИМ
     спіном на 2000 ₽, і гравець із грошима на балансі перетворює бонус
     на підкидання монетки. Саме тому ліміт ставки є в правилах кожного
     казино; 10% від суми бонусу — звичайна величина.

   BONUS_DAYS — скільки живе невідіграний бонус. Далі згорає разом із
     замкненою сумою. Інакше подарунок висить на балансі вічно,
     роздуваючи видиме число й нічого не значачи.

   BONUS_MAX_CASHOUT_X — у скільки разів від суми бонусу можна забрати.
     Це захист від однієї ситуації: безкоштовні 100 ₽ ловлять x500 і
     перетворюються на 50 000 ₽ виплати. На безкоштовні гроші стеля
     стоїть у будь-якому казино.
   ============================================================ */

