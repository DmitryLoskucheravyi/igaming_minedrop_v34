/* ============================================================
   ВИВЕДЕННЯ КОШТІВ.

   Дзеркало депозиту, але гроші йдуть у зворотний бік, і через це
   порядок принципово інший.

   ДЕПОЗИТ: заявка -> гравець переказує -> адмін бачить надходження ->
   погоджує -> баланс ЗАРАХОВАНО.

   ВИВЕДЕННЯ: заявка -> баланс СПИСАНО ОДРАЗУ -> адмін відправляє
   USDT -> погоджує (баланс уже списаний, більше нічого не робимо).
   Відхилив або гравець скасував — гроші ПОВЕРТАЮТЬСЯ.

   Списання саме в момент заявки — не дрібниця. Інакше гравець замовляє
   виплату й далі грає тими самими грошима: програв — на балансі нуль,
   а заявка все одно чекає виплати.

   Строку давності тут немає (на відміну від депозиту з його 30 хв):
   заявка чекає на людину, а не на переказ. Поки вона pending, гравець
   може скасувати її сам.
   ============================================================ */

export type WithdrawMethod = 'usdt_trc20';

export type WithdrawStatus =
  | 'pending'    // чекає рішення адміна, гроші вже зарезервовані
  | 'approved'   // адмін відправив кошти
  | 'rejected'   // адмін відхилив, гроші повернуто
  | 'canceled';  // гравець скасував сам, гроші повернуто

export interface WithdrawRecord {
  id: string;
  telegramId: number;
  method: WithdrawMethod;

  /** скільки списано з балансу, ₽ */
  amount: number;
  /** скільки відправити гравцю, USDT (за курсом на момент заявки) */
  usdtAmount: number;
  rate: number;
  /** курс на момент заявки був приблизний — сума може не збігатись із ринком */
  rateApprox?: boolean;

  /** куди відправляти — адреса ГРАВЦЯ (на відміну від депозиту, де
      адреса наша) */
  address: string;

  status: WithdrawStatus;
  createdAt: number;
  resolvedAt?: number;
  /** нотатка адміна при відхиленні */
  adminNote?: string;
}

