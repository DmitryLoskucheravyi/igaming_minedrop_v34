/* ============================================================
   КУПЛЕНІ ФРІСПІНИ — лінійка пакетів.

   Гравець платить один раз і отримує пакет прокрутів, у яких
   ЙМОВІРНІСТЬ КІРКИ вдвічі вища за звичайну. Це не «щасливий режим» і
   не підкручений результат: множник заходить у ту саму рулетку тим
   самим способом, що й pity, і клієнт відтворює її з того самого сида
   (RoundResult.chanceX) — інакше він просто розійшовся б із сервером.

   ЧОМУ ПАКЕТИ, А НЕ «СКІЛЬКИ ЗАВГОДНО ПРОКРУТІВ НА БУДЬ-ЯКІЙ СТАВЦІ».
   Пакет — це рядок у списку з власною картинкою й однією ціною. Вибір
   із п'яти готових рядків зрозуміліший за два незалежні повзунки
   (кількість × ставка), а математика від цього не страждає: ціна
   кожного пакета рахується тією самою формулою.

   ---- ЗВІДКИ ЦІНА ----
   Заміряно на 40 000 прокрутів: звичайний спін віддає 68.9% ставки
   (решту до 96% додає гарантія після серії промахів — на куплені
   прокрути вона не діє, див. нижче), а спін із подвоєним шансом —
   135.2%. Щоб віддача покупки лишилась тими самими 96%, один прокрут
   має коштувати 1.352 / 0.96 ≈ 1.408 ставки.

   ГАРАНТІЯ (pity) НА КУПЛЕНІ ПРОКРУТИ НЕ ДІЄ — як і на бонус бай та
   виграну бонуску. Серія промахів належить звичайній грі на конкретній
   ставці, і покупка не має ані з'їдати її, ані підживлювати. Саме тому
   в розрахунку ціни стоїть 135.2%, а не більше.

   ---- ВИГРАШ ІЗ ЦИХ ПРОКРУТІВ — ЗВИЧАЙНІ ГРОШІ ----
   Без замка: пакет куплено за власні, а відіграш вішають на подарунки.
   Спершу виграш замикався на x10, і це робило пакет грабіжницьким —
   при ціні 35.2 ставки, середньому виграші 33.8 і цілі відіграшу в 338
   ставок фактична віддача падала до ~57%. Натомість у оборот іде сама
   ціна пакета (players.buySpins) — як ставка, якою вона і є.
   ============================================================ */

/** у скільки разів вища ймовірність кірки в цих прокрутах */
export const FS_CHANCE_X = 2;

/** ціна ОДНОГО прокруту у ставках (див. розрахунок вище) */
export const FS_PRICE_X = 1.408;

export interface SpinPack {
  id: string;
  /** скільки прокрутів у пакеті */
  spins: number;
  /** на якій ставці вони грають */
  bet: number;
  /** як показуємо в списку */
  name: string;
}

/* Лінійка: від дешевої проби до великого пакета. Ставка в пакеті
   ФІКСОВАНА й зберігається разом із ним — інакше пакет, куплений на 10,
   можна було б відіграти на 2000. */
export const SPIN_PACKS: readonly SpinPack[] = [
  { id: 'p10x10', spins: 10, bet: 10, name: 'Проба' },
  { id: 'p25x10', spins: 25, bet: 10, name: 'Малый' },
  { id: 'p25x50', spins: 25, bet: 50, name: 'Средний' },
  { id: 'p50x50', spins: 50, bet: 50, name: 'Большой' },
  { id: 'p50x100', spins: 50, bet: 100, name: 'Максимум' },
];

export const packPrice = (pack: SpinPack): number =>
  Math.round(pack.spins * pack.bet * FS_PRICE_X);

export const packById = (id: string): SpinPack | undefined =>
  SPIN_PACKS.find((p) => p.id === id);
