/* ============================================================
   КУПЛЕНІ ФРІСПІНИ.

   Гравець платить один раз і отримує пакет прокрутів, у яких
   ЙМОВІРНІСТЬ КІРКИ вдвічі вища за звичайну. Це не «щасливий режим» і
   не підкручений результат: множник заходить у ту саму рулетку тим
   самим способом, що й pity, і клієнт відтворює її з того самого сида
   (RoundResult.chanceX) — інакше він просто розійшовся б із сервером.

   ЦІНА — У СТАВКАХ, а не в рублях. Пакет грається на тій ставці, за
   якою куплений, тож і коштувати він мусить пропорційно: інакше
   фіксована ціна на ставці 10 була б грабунком, а на 2000 — подарунком.

   Звідки взявся множник ціни. Заміряно на 40 000 прокрутів: звичайний
   спін віддає 68.9% ставки (решту до 96% додає гарантія після серії
   промахів — на куплені прокрути вона не діє, див. нижче), а спін із
   подвоєним шансом — 135.2%. Пакет із 25 таких прокрутів очікувано
   поверне 33.8 ставки, і щоб віддача покупки лишилась тими самими 96%,
   ціна має бути 33.8 / 0.96 ≈ 35.2 ставки.

   ГАРАНТІЯ (pity) НА КУПЛЕНІ ПРОКРУТИ НЕ ДІЄ — як і на бонус бай та
   виграну бонуску. Причина та сама: серія промахів належить звичайній
   грі на конкретній ставці, і подарунок чи покупка не мають ані
   з'їдати її, ані підживлювати. Саме тому в розрахунку ціни вище
   стоїть 135.2%, а не більше.
   ============================================================ */

/** скільки прокрутів у пакеті */
export const FS_PACK = 25;

/** у скільки разів вища ймовірність кірки в цих прокрутах */
export const FS_CHANCE_X = 2;

/** ціна пакета у ставках (ціна = ставка * це число) */
export const FS_PRICE_X = 35.2;

/* ВИГРАШ ІЗ ЦИХ ПРОКРУТІВ — ЗВИЧАЙНІ ГРОШІ, без замка.

   Спершу він замикався на x10, як реферальні виплати. Порахували —
   вийшло, що пакет ціною 35.2 ставки при середньому виграші 33.8
   ставки й цілі відіграшу в 338 ставок давав фактичну віддачу ~57%
   замість 96%, під які рахувалась ціна. Замок тихо перетворював чесний
   продукт на грабіжницький, тому знятий: відіграш вішають на подарунки,
   а пакет купують за власні гроші.

   Сама ціна пакета при цьому йде в оборот (players.buySpins) — як
   ставка, якою вона і є. */

export const spinsPrice = (bet: number): number => Math.round(bet * FS_PRICE_X);
