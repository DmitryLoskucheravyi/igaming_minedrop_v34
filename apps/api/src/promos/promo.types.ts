/* ============================================================
   ПРОМОКОДИ — надбавка до депозиту у відсотках.

   Адмін заводить у CRM код і відсоток; гравець вписує код у вікні
   поповнення; коли заявку погоджено, на бонусний баланс лягає
   amount * percent / 100.

   ДВІ РЕЧІ, ЯКІ ТУТ ВИРІШЕНО РАЗ І НАЗАВЖДИ.

   1. Надбавка — БОНУСНІ гроші, а не готівка. Це не смак, а те саме
      правило, за яким живуть подарунки колеса й рефералки: гравець цих
      грошей не заносив, тому вивести їх можна лише через відіграш
      (PROMO_WAGER_X). Інакше промокод — це банкомат: завів код,
      поповнив, зняв поповнення разом із надбавкою.

   2. Відсоток ЗАМОРОЖУЄТЬСЯ в заявці в момент її створення. Гравцеві
      показали «+20%» — значить, він і отримає 20%, навіть якщо адмін
      тим часом вимкнув код або змінив відсоток. Змінене правило діє на
      наступні заявки, а не заднім числом на вже видану обіцянку.
   ============================================================ */

/** Скільки разів треба прокрутити надбавку, щоб її вивести.

    Стільки ж, скільки на реферальних грошах (REF_BONUS_WAGER_X): і те,
    і те — подарунок, а не внесені гравцем кошти, тож і вимога однакова.
    Власний депозит відіграшу не вимагає взагалі. */
export const PROMO_WAGER_X = 10;

/** Стеля відсотка. 500% — свідомо високо: це запобіжник від зайвого
    нуля в полі CRM, а не ігровий ліміт. */
export const PROMO_MAX_PERCENT = 500;

export const PROMO_CODE_MAX = 32;

export interface PromoCode {
  id: string;
  /** завжди у верхньому регістрі — див. normalizeCode */
  code: string;
  /** скільки відсотків від суми депозиту йде бонусом */
  percent: number;
  /** вимкнений код не застосовується, але лишається в історії */
  active: boolean;
  createdAt: number;
  /** скільки разів код спрацював на погодженій заявці */
  used: number;
  /** скільки всього ₽ видано бонусом за цим кодом */
  granted: number;
}

/* Код нечутливий до регістру й пробілів: гравець копіює його з
   оголошення разом із чим завгодно, і «промокод не найден» через
   зайвий пробіл — це не захист, а втрачений депозит. */
export function normalizeCode(raw: string): string {
  return raw.trim().toUpperCase().slice(0, PROMO_CODE_MAX);
}
