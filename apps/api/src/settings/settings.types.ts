import type { NetworkId, TokenId } from '../payments/networks';

/* ============================================================
   НАЛАШТУВАННЯ ПРИЙОМУ — те, що адмін міняє на ходу, без деплою.

   Режим автопідтвердження навмисно має чотири стани, а не «увімк/вимк».
   Довіряти боту баланси одразу — погана ідея: помилка в зіставленні
   переказу із заявкою помітна не тоді, коли її бачиш у логах, а тоді,
   коли гроші вже нараховані не тому.

     off   — спостерігач не працює взагалі;
     watch — бачить перекази й пише в лог «зарахував би цю заявку»,
             але не чіпає нічого. Так дивишся день і звіряєш;
     semi  — сам знаходить переказ і ПОЗНАЧАЄ заявку оплаченою,
             кнопку «зарахувати» лишає адміну. Один клік замість
             пошуку по блокчейну;
     auto  — зараховує сам.
   ============================================================ */
export type DepositMode = 'off' | 'watch' | 'semi' | 'auto';

export interface DepositSettings {
  mode: DepositMode;
  /** які мережі показуємо гравцю й слухаємо */
  networks: NetworkId[];
  /** які токени приймаємо */
  tokens: TokenId[];
}

