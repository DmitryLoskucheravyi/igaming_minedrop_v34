import type { NetworkId, TokenId } from './networks';

/* ============================================================
   НЕОПІЗНАНІ ПЛАТЕЖІ.

   Переказ прийшов на нашу адресу, але не зіставився з жодною заявкою:
   гравець надіслав після протухання, помилився в сумі, відправив без
   заявки взагалі або двічі.

   Ігнорувати такі перекази не можна — це справжні гроші, які вже в нас.
   Заявка протухає за 30 хвилин, а гроші в мережі не протухають ніколи,
   тому спостерігач слухає адреси НЕЗАЛЕЖНО від того, чи є активні
   заявки, і все незіставлене складає сюди, а не викидає.

   Далі адмін вирішує вручну: знайти гравця й нарахувати або лишити.
   ============================================================ */

export type UnmatchedStatus = 'new' | 'credited' | 'ignored';

export interface UnmatchedPayment {
  id: string;
  network: NetworkId;
  token: TokenId;
  /** наша адреса, на яку прийшло */
  address: string;
  /** звідки прийшло — часто це адреса біржі, але буває й гаманець гравця */
  from: string;
  /** скільки прийшло, у токені */
  amount: number;
  txid: string;
  /** час переказу в мережі */
  at: number;
  /** коментар до переказу, якщо мережа їх підтримує */
  memo?: string;

  status: UnmatchedStatus;
  seenAt: number;
  resolvedAt?: number;
  /** кому зарахували, якщо зарахували */
  creditedTo?: number;
  creditedRub?: number;
  adminNote?: string;
}
