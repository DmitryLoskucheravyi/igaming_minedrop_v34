/* ============================================================
   PAYMENTS — заявки на депозит.

   Потік:
     1. гравець створює заявку (сума в ₽, метод usdt_trc20);
     2. отримує адресу гаманця + точну суму USDT + таймер 30 хв;
        більше нічого не тисне;
     3. переказує USDT ззовні;
     4. адмін бачить заявку в CRM, звіряє транзакцію в мережі,
        погоджує (approved -> баланс зараховано) або скасовує (rejected);
        гравець, який ще не переказав, може зняти заявку сам (canceled);
     5. якщо за PAYMENT_TTL_MS підтвердження немає — заявка стає expired.
   ============================================================ */

import type { Family, NetworkId, TokenId } from './networks';

/* Метод лишився як рядок сумісності зі старими документами в базі.
   Тепер спосіб описують два поля: network + token. */
export type PaymentMethod = 'usdt_trc20' | 'crypto';

export type PaymentStatus =
  | 'pending'      // створена, чекаємо переказ + рішення адміна
  /* Бот знайшов переказ у мережі й тримає заявку, доки той не
     «відлежиться» finalitySec. Це НЕ проміжна косметика: до фіналізації
     блок ще може відкотитись, і зараховувати такі гроші рано.

     Заявка в цьому стані НЕ ПРОТУХАЄ. Тридцять хвилин відміряні на те,
     щоб людина встигла переказати; вона встигла — далі чекає мережа, і
     карати за її повільність нема за що. */
  | 'processing'
  | 'approved'     // підтверджено (ким — у resolvedBy), баланс зараховано
  | 'rejected'     // відхилено (ким — у resolvedBy)
  | 'expired'      // 30 хв минуло без переказу
  /* Гравець сам зняв заявку, ще не переказавши. Окремий статус, а не
     'expired' і не 'rejected': перше збрехало б про причину в історії,
     друге виглядало б як відмова адміна — і людина писала б у підтримку
     питати, за що її відхилили.

     Скасувати можна ТІЛЬКИ pending. Заявка в processing означає, що
     переказ уже знайдено в мережі; закрити її з телефона — це викинути
     гроші, які вже пішли. */
  | 'canceled';

/* Хто закрив заявку. Різниця не косметична: розбираючи скаргу, треба
   бачити, це рішення людини чи бота — і в другому випадку шукати
   причину в логах спостерігача, а не питати адміна, що він натиснув. */
export type ResolvedBy = 'admin' | 'bot';

/* Гаманець-приймач. Адрес кілька, адмін керує ними в CRM. Кожну
   заявку прив'язуємо до однієї адреси (по можливості вільної), щоб
   адмін розрізняв, за яку саме заявку прийшли кошти. */
export interface DepositAddress {
  id: string;
  address: string;
  /* Адреса належить РОДИНІ, а не мережі: одна 0x-адреса приймає в
     шести EVM-мережах одразу. Тому вибирати адресу під заявку треба
     за родиною тієї мережі, яку обрав гравець. */
  family: Family;
  /** заголовок для адмінки, щоб не плутати адреси */
  label?: string;
  active: boolean;
  createdAt: number;

  /* ---- те, що потрібно спостерігачу ----

     Адреси заводяться й вимикаються в CRM на ходу, тому спостерігач не
     тримає власного списку: він щоразу питає watchTargets(). Додав
     адресу — вона в роботі з наступного циклу, без рестарту.

     watchFrom — З ЯКОГО МОМЕНТУ дивитись. Обов'язково: гаманець може
     бути не новий, і без цієї межі перший же цикл підняв би всю його
     історію й спробував зарахувати перекази трирічної давності. */
  watchFrom: number;
  /** де спостерігач зупинився минулого разу (формат — його справа) */
  cursor?: string;
  /** коли востаннє дивились цю адресу */
  scannedAt?: number;
}

export interface PaymentRecord {
  id: string;
  telegramId: number;
  method: PaymentMethod;

  /** у якій мережі й яким токеном платить гравець */
  network: NetworkId;
  token: TokenId;

  /** скільки нарахувати на баланс, ₽ */
  amount: number;
  /** скільки переказати в токені (за курсом на момент створення) */
  usdtAmount: number;
  /* Унікальний дріб, доданий до суми, щоб пара «адреса + сума» точно
     вказувала на цю заявку. У мережах із коментарем (TON) не потрібен —
     там ідентифікує memo. */
  memo?: string;
  /** курс ₽/USDT, зафіксований при створенні */
  rate: number;
  /** курс на момент створення був ПРИБЛИЗНИЙ: біржа не відповідала,
      працював fallback або застаріле значення. Сума USDT у такій заявці
      може не збігатися з ринком — і гравець, і адмін мусять це бачити,
      а не дізнаватись постфактум. */
  rateApprox?: boolean;
  /** адреса гаманця, куди переказувати (копія рядка на момент створення) */
  address: string;
  /** id адреси з пулу (може вже не існувати, якщо адмін її видалив) */
  addressId?: string;

  status: PaymentStatus;
  /** хто погодив/відхилив: адмін чи бот */
  resolvedBy?: ResolvedBy;
  createdAt: number;
  /** createdAt + PAYMENT_TTL_MS */
  expiresAt: number;
  /** коли адмін погодив/скасував або коли протухла */
  resolvedAt?: number;

  /* ---- те, що заповнює спостерігач ----
     txid — ідентифікатор переказу в мережі. Він же й захист від
     подвійного зарахування: один переказ не може закрити дві заявки. */
  txid?: string;
  /** скільки НАСПРАВДІ прийшло, у токені */
  paidAmount?: number;
  /** коли переказ знайдено в мережі */
  matchedAt?: number;
  /* Раніше цього моменту переказ не вважається остаточним:
     matchedAt + finalitySec мережі. Доти заявка висить у processing. */
  confirmAt?: number;
  /** коли переказ визнано остаточним (мережа його підтвердила) */
  confirmedAt?: number;
  /** нотатка адміна при скасуванні (необов'язково) */
  adminNote?: string;
}

/** Публічний зріз для клієнта/CRM (усе, крім нічого — тут секретів нема). */
export type PaymentView = PaymentRecord;

export const PAYMENT_TTL_MS = 30 * 60 * 1000;   // 30 хв
export const PAYMENT_MIN_RUB = 100;
export const PAYMENT_MAX_RUB = 5_000_000;
