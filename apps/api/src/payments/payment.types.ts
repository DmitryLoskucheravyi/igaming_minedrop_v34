/* ============================================================
   PAYMENTS — заявки на депозит.

   Потік:
     1. гравець створює заявку (сума в ₽, метод usdt_trc20);
     2. отримує адресу гаманця + точну суму USDT + таймер 30 хв;
        більше нічого не тисне;
     3. переказує USDT ззовні;
     4. адмін бачить заявку в CRM, звіряє транзакцію в мережі,
        погоджує (approved -> баланс зараховано) або скасовує (rejected);
        гравець, який ще не переказав, може зняти заявку сам (canceled);
     5. якщо за PAYMENT_TTL_MS підтвердження немає — заявка стає expired.
   ============================================================ */

import type { Payment } from '@minedrop/contracts';
import type { Family, NetworkId, TokenId } from './networks';

/* Метод лишився як рядок сумісності зі старими документами в базі.
   Тепер спосіб описують два поля: network + token. */
/* Статуси й спосіб оплати — у @minedrop/contracts: їх читають і гра, і
   CRM, і розійтись вони не мають права. Перевипускаємо, щоб серверний
   код звертався до них там, де описана й решта моделі заявки. */
export type { PaymentMethod, PaymentStatus, ResolvedBy } from '@minedrop/contracts';

/* Гаманець-приймач. Адрес кілька, адмін керує ними в CRM. Кожну
   заявку прив'язуємо до однієї адреси (по можливості вільної), щоб
   адмін розрізняв, за яку саме заявку прийшли кошти. */
export interface DepositAddress {
  id: string;
  address: string;
  /* Адреса належить РОДИНІ, а не мережі: одна 0x-адреса приймає в
     шести EVM-мережах одразу. Тому вибирати адресу під заявку треба
     за родиною тієї мережі, яку обрав гравець. */
  family: Family;
  /** заголовок для адмінки, щоб не плутати адреси */
  label?: string;
  active: boolean;
  createdAt: number;

  /* ---- те, що потрібно спостерігачу ----

     Адреси заводяться й вимикаються в CRM на ходу, тому спостерігач не
     тримає власного списку: він щоразу питає watchTargets(). Додав
     адресу — вона в роботі з наступного циклу, без рестарту.

     watchFrom — З ЯКОГО МОМЕНТУ дивитись. Обов'язково: гаманець може
     бути не новий, і без цієї межі перший же цикл підняв би всю його
     історію й спробував зарахувати перекази трирічної давності. */
  watchFrom: number;
  /** де спостерігач зупинився минулого разу (формат — його справа) */
  cursor?: string;
  /** коли востаннє дивились цю адресу */
  scannedAt?: number;
}

/* Серверний запис = те, що їде клієнту (контракт Payment), плюс те, що
   назовні не потрібне. Розширенням, а не копією: додане в контракт поле
   з'явиться тут само, і розійтись вони вже не можуть. */
export interface PaymentRecord extends Payment {
  /** id адреси з пулу (може вже не існувати, якщо адмін її видалив) */
  addressId?: string;
}

/** Публічний зріз для клієнта/CRM (усе, крім нічого — тут секретів нема). */
export type PaymentView = PaymentRecord;

/* ============================================================
   ЩО БАЧИТЬ І ЩО СЛУХАЄ СПОСТЕРІГАЧ

   Ці два типи жили в payments.service, і через них ПОРТ читача мережі
   (watcher/chain.types) імпортував реалізацію свого ж споживача —
   залежність, спрямована рівно навпаки. Тут вони на своєму місці: це
   опис домену платежів, а не деталь конкретного сервісу.
   ============================================================ */

/** Прийшов переказ у мережі — рівно те, що бачить спостерігач. */
export interface IncomingTx {
  network: NetworkId;
  token: TokenId;
  /** наша адреса-отримувач */
  to: string;
  from: string;
  /** сума в токені, вже поділена на decimals */
  amount: number;
  txid: string;
  /** час переказу в мережі, мс */
  at: number;
  memo?: string;
  /* Переказ виглядає не так, як має, і сумі в ньому вірити не можна.

     Єдиний випадок на сьогодні — знаки після коми з API не збіглися з
     каталогом (networks.ts). Помилитись тут означало б зарахувати в
     мільйон разів більше, тож такий переказ не зіставляється з
     заявкою НІКОЛИ, а йде адміну з цим поясненням. Викидати його не
     можна: гроші справжні й уже в нас. */
  suspect?: string;
}

/* Одна адреса + усе, що спостерігачу треба знати, щоб її слухати.
   Формується на льоту з поточних адрес і поточних налаштувань, тому
   окремої копії списку ніде немає й розсинхрону теж. */
export interface WatchTarget {
  addressId: string;
  address: string;
  family: Family;
  label?: string;
  /** раніше цього моменту перекази не наші — це історія гаманця */
  watchFrom: number;
  cursor?: string;
  scannedAt?: number;
  /** мережі цієї родини, увімкнені просто зараз */
  networks: NetworkId[];
  /** монети, які приймаємо просто зараз */
  tokens: TokenId[];
}

/* ---- дріб, який робить пару «адреса + сума» унікальною ----

   У TRON, EVM і Solana немає коментаря до переказу, тому заявку
   впізнають за сумою. 0.0001..0.0099 — сто варіантів на адресу, і
   виглядає це як звичайне округлення курсу, а не як код. */
export const MEMO_STEPS = 99;
export const MEMO_UNIT = 0.0001;

/* Наскільки сума переказу може розійтися з очікуваною, щоб її все одно
   визнали тією самою. Половина кроку дробу: більший допуск склеїв би
   дві сусідні заявки на одній адресі, і зіставлення стало б здогадкою. */
export const AMOUNT_EPS = MEMO_UNIT / 2;

export const PAYMENT_TTL_MS = 30 * 60 * 1000;   // 30 хв
export const PAYMENT_MIN_RUB = 100;
export const PAYMENT_MAX_RUB = 5_000_000;
