/* Панель у css-проценти. Рахуємо тут, а не в розмітці, щоб формула була
   одна на всі написи й не розповзлась по компоненту. */
export function plateStyle(p: BannerPlate): React.CSSProperties {
  const [x0, y0, x1, y1] = p.box;
  return {
    left: `${x0 * 100}%`,
    top: `${y0 * 100}%`,
    width: `${(x1 - x0) * 100}%`,
    height: `${(y1 - y0) * 100}%`,
  };
}
