/* ============================================================
   БАНЕРИ ПАКЕТІВ ФРІСПІНІВ — картинка плюс координати панелей.

   Кожен пакет у списку — намальований банер (public/spins) із чотирма
   порожніми панелями, у які компонент вписує назву, кількість
   прокрутів, множник шансу й ціну. Числа не вшиті в картинку: ціна
   рахується з конфігу сервера, і кожна її зміна означала б
   перемальовування всіх файлів.

   ГЕОМЕТРІЯ В КОЖНОГО БАНЕРА СВОЯ. З картками бонус бая пощастило —
   там три з чотирьох збіглися панель у панель. Тут не збіглося жодне:
   генератор щоразу зсуває панелі на 10-40 px, і це видно заміром.
   Тому в кожного рядка власні координати, зняті з ЙОГО файлу — по
   темній середині панелі, а не по золотій рамці: у рамки світлий
   відблиск згори, і маска по ній ловить лише нижню половину.

   Перемалюють банери за спільним шаблоном — числа просто зійдуться, і
   таблицю можна буде згорнути в одну константу. Поки що чесніше
   тримати заміряне.
   ============================================================ */

export interface BannerPlate {
  /** [x0, y0, x1, y1] у частках картинки */
  box: [number, number, number, number];
}

export interface BannerGeometry {
  title: BannerPlate;
  left: BannerPlate;
  right: BannerPlate;
  price: BannerPlate;
}

