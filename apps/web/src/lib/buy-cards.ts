/* ============================================================
   КАРТКИ БОНУС БАЮ — картинка плюс координати порожніх панелей.

   Малюнок картки (рамка, фон, кірка) намальований, а ВСІ ЧИСЛА
   накладаються поверх програмно: назва, міцність, урон і ціна залежать
   від тіру та поточної ставки, і вшивати їх у картинку означало б
   перемальовувати всі чотири файли після кожної зміни балансу.

   Координати — у ЧАСТКАХ від розміру картинки (687x1024), тому картка
   масштабується під будь-який екран, а написи їдуть разом із нею.

   ГЕОМЕТРІЯ ОДНА НА ВСІХ, і це не припущення, а замір: у всіх чотирьох
   картках панелі стоять на тих самих пікселях (розбіжність ≤ 1 px —
   артефакт jpeg). Перша версія залізної була зі зсувом, і тут лежав
   окремий блок координат під неї; картку перемалювали під спільний
   шаблон, і блок став непотрібен.

   Міряно по ТЕМНІЙ СЕРЕДИНІ панелі, а не по золотій рамці: у рамки є
   світлий відблиск згори, маска по ній ловила лише нижню половину, і
   написи сідали під самий край.

   Нова картка? Досить переміряти той самий прямокутник і, якщо він
   збігається, просто додати рядок у BUY_CARDS. */

export interface CardPlate {
  /** межі панелі в частках картинки: [x0, y0, x1, y1] */
  box: [number, number, number, number];
}

export interface CardGeometry {
  title: CardPlate;
  left: CardPlate;
  right: CardPlate;
  price: CardPlate;
}

const rect = (
  x0: number, y0: number, x1: number, y1: number,
): CardPlate => ({ box: [x0 / 687, y0 / 1024, x1 / 687, y1 / 1024] });

/* Спільна геометрія — заміряна по всіх чотирьох картках. */
const CANON: CardGeometry = {
  title: rect(124, 112, 562, 209),
  left: rect(94, 706, 324, 803),
  right: rect(362, 706, 592, 803),
  price: rect(94, 838, 592, 935),
};

export interface BuyCard {
  src: string;
  geom: CardGeometry;
}

/* Ключ — id тіру з рушія (TIERS), щоб картка знаходилась тим самим
   ідентифікатором, яким сервер називає покупку. */
export const BUY_CARDS: Record<string, BuyCard> = {
  lvl2: { src: '/cards/wooden.jpg', geom: CANON },
  lvl3: { src: '/cards/stone.jpg', geom: CANON },
  lvl4: { src: '/cards/iron.jpg', geom: CANON },
  diamond: { src: '/cards/diamond.jpg', geom: CANON },
};

/** Співвідношення сторін картки — щоб верстка не гадала розмір. */
export const CARD_ASPECT = 687 / 1024;

/* Панель у css-проценти: left/top/width/height від контейнера картки.
   Рахуємо тут, а не в розмітці, щоб формула була одна на всі чотири
   написи й не розповзлась по компоненту. */
export function plateStyle(p: CardPlate): React.CSSProperties {
  const [x0, y0, x1, y1] = p.box;
  return {
    left: `${x0 * 100}%`,
    top: `${y0 * 100}%`,
    width: `${(x1 - x0) * 100}%`,
    height: `${(y1 - y0) * 100}%`,
  };
}
