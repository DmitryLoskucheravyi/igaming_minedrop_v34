export type PixIconName = keyof typeof ICONS;

/* Клітинка — 3 одиниці при viewBox 24: 8 * 3 = 24 рівно, тож сітка
   лягає на цілі числа й краї не мажуться навіть при масштабуванні. */
const CELL = 3;

export function PixIcon({ name }: { name: PixIconName }) {
  const grid = ICONS[name];
  const cells: string[] = [];
  grid.forEach((row, r) => {
    [...row].forEach((ch, c) => {
      if (ch === '#') cells.push(`M${c * CELL} ${r * CELL}h${CELL}v${CELL}h-${CELL}z`);
    });
  });
  return (
    <svg className="pixicon" viewBox="0 0 24 24" aria-hidden="true">
      <path d={cells.join('')} />
    </svg>
  );
}
