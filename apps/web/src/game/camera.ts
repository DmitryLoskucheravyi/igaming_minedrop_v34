/* ============================================================
   КАМЕРА — яку частину шахти зараз видно.

   Координати в КЛІТИНКАХ, як і вся фізика: x/y — лівий верхній кут
   видимої області. Переклад у пікселі робить project(), і для нього
   потрібен масштаб (cell), який рахує розкладка презентера — камера
   його не знає й не має знати.

   Що тут принципово, крім арифметики:

   ГОРТАННЯ ЗАБИРАЄ КЕРУВАННЯ. Поки палець на екрані (panning) і ще
   PAN_HOLD секунд після, follow() не рухає кадр узагалі. Час цієї
   паузи РЕАЛЬНИЙ, а не прискорений: на швидкості ×4 вона інакше
   стискалась би до чвертки секунди, і камера відбирала б кадр у
   гравця майже одразу.

   ПРУНИНГ. Вище певної межі рушій ряди вже викинув, і намальовані там
   блоки будуть свіжозгенерованими, тобто цілими. Тому clampToPrune()
   тримає верх кадру нижче за неї, хоч би звідки прийшов рух —
   гортання, зум чи власний лерп.
   ============================================================ */

import { CONFIG, PRUNE_MARGIN } from '@minedrop/engine';

/** Куди дивитись, поки йде забіг: позиція кірки в клітинках. */
export interface FollowTarget {
  x: number;
  y: number;
}

export class Camera {
  /** лівий верхній кут видимої області, у клітинках */
  x = 0;
  y = 0;
  /** де камера стоїть, поки забігу немає */
  idleX = 0;
  minY = 0;

  /* Гравець гортає поле пальцем. Доки panning === true, лічильник
     panT не йде взагалі: інакше пауза застигання пальця на екрані
     витрачалась би даремно. */
  panning = false;
  panT = 0;

  /** Тап/жест почався: камера мовчить, доки палець не зникне. */
  grab(): void {
    this.panning = true;
  }

  /** Палець зник — камера мовчить ще hold секунд. */
  release(hold: number): void {
    if (!this.panning) return;
    this.panning = false;
    this.panT = hold;
  }

  /** Скинути гортання (новий раунд забирає керування назад одразу). */
  reset(): void {
    this.panning = false;
    this.panT = 0;
  }

  /** Поставити кадр у спокійне положення — під рулеткою й між раундами. */
  toIdle(): void {
    this.x = this.idleX;
    this.y = this.minY;
  }

  /** Зсув пальцем по вертикалі (px -> клітинки), з обмеженням. */
  panBy(dyCells: number, lo: number, hi: number): void {
    this.y -= dyCells;
    if (this.y < lo) this.y = lo;
    else if (this.y > hi) this.y = hi;
  }

  /* Масштаб змінився. camX/camY — лівий верхній кут кадру, тому сама
     лише зміна cell тягне світ від краю екрана, і при віддаленні поле
     повзе вбік. Тому запам'ятовуємо світову точку, що зараз у центрі,
     і після зміни масштабу повертаємо її рівно туди ж. */
  centerAfterZoom(before: { cx: number; cy: number }, w: number, h: number, cell: number): void {
    this.x = before.cx - w / cell / 2;
    this.y = before.cy - h / cell / 2;
  }

  centerNow(w: number, h: number, cell: number): { cx: number; cy: number } {
    return { cx: this.x + w / cell / 2, cy: this.y + h / cell / 2 };
  }

  /* Плавне ведення за кіркою.

     Раніше камера їхала ТІЛЬКИ вниз і тільки по вертикалі — по суті
     стеля, що повзе за найглибшою кіркою. Тепер кірка відскакує вгору
     й ходить по всій ширині поля, тому камера має встигати в будь-який
     бік. Обмеження знизу (minY) лишається лише для стану БЕЗ забігу —
     щоб під рулеткою поверхня стояла там само, де й стояла.

     dt — прискорений час раунду (ним іде лерп), dtReal — справжній
     (ним тане пауза після гортання). */
  follow(
    dt: number, dtReal: number,
    view: number, target: FollowTarget | null, hasRun: boolean, h: number, cell: number,
  ): void {
    if (this.panning) return;              // палець на екрані — відлік не почався
    if (this.panT > 0) {
      this.panT = Math.max(0, this.panT - dtReal);
      return;
    }

    let tx = this.idleX;
    let ty = this.minY;
    if (target) {
      /* Поле влазить у кадр цілком (гравець відвів камеру далеко) —
         тримаємо по центру САМЕ ПОЛЕ. Інакше камера й далі центрувала б
         кірку, і шахта з'їжджала б ліворуч або праворуч залежно від
         того, де кірка зараз. Поки поле ширше за кадр, центруємо
         кірку, як і було. */
      tx = view >= CONFIG.cols ? (CONFIG.cols - view) / 2 : target.x - view / 2;
      ty = target.y - (h * CONFIG.camLead) / cell;
    }

    const k = Math.min(1, dt * CONFIG.camLerp);
    this.x += (tx - this.x) * k;
    this.y += (ty - this.y) * k;
    /* Саме hasRun, а не наявність цілі: забіг може вже йти, а кірки
       для ведення ще не бути (усі відпрацювали). Тоді кадр лишається
       де стоїть — так було й до розділення. */
    if (!hasRun && this.y < this.minY) this.y = this.minY;
  }

  /** Верх кадру не має підійматись вище за межу прунингу. */
  clampToPrune(topCell: number): void {
    const limit = topCell - (PRUNE_MARGIN - 8);
    if (this.y < limit) this.y = limit;
  }

  /** Кадр не піднімається вище спокійного положення поза забігом. */
  clampIdle(): void {
    if (this.y < this.minY) this.y = this.minY;
  }
}
