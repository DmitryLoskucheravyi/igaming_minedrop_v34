/* Таблиця прокруту рулетки: «пусто» + усі кірки.
   null у полі tier = «пусто». */
export interface ReelSlot { tier: Tier | null; weight: number }

export function reelTable(): ReelSlot[] {
  const table: ReelSlot[] = [{ tier: null, weight: CONFIG.nothingWeight }];
  for (const t of TIERS) table.push({ tier: t, weight: t.weight });
  return table;
}

/* Тільки кірки, без «пусто» — для pity-прокруту (гарантована кірка).
   Розклад тірів той самий, що на звичайній рулетці. */
export function tierOnlyTable(): ReelSlot[] {
  return TIERS.map((t): ReelSlot => ({ tier: t, weight: t.weight }));
}

/* Таблиця множників БОНУСНОЇ шахти: ті самі номінали, але великі ікси
   важчі за CONFIG.buy.tailBoost. Дрібні не чіпаються й просто втрачають
   частку.

   Будується один раз на модуль. На детермінізм підміна не впливає:
   pickWeighted() витрачає рівно один виклик rnd() незалежно від вмісту
   таблиці, а про bonus клієнт і сервер знають однаково. */
export const MULT_TABLE_BONUS: readonly { m: number; weight: number }[] =
  CONFIG.mult.table.map((e) => ({
    m: e.m,
    weight: e.weight * (CONFIG.buy.tailBoost[e.m] ?? 1),
  }));
