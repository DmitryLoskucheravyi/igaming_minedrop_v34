/* ============================================================
   RUN — фізика забігу. Чиста логіка, без малювання:
   клієнт її рендерить, сервер ганяє до кінця в одному циклі,
   sim/*.ts — тисячами.

   Зараз у забігу рівно одна кірка. Код лишається розрахованим на
   кілька (спільний рахунок, події з полем pick) — це точка
   розширення, а не мертвий випадок.

   Кірка падає, б'є блок, ПЕРЕВЕРТАЄТЬСЯ і через це зісковзує вбік,
   тому летить по діагоналі, а не тупо вниз. Діагональ — наслідок
   обертання й тертя на грані (див. resolveContact), а не окремий
   бічний поштовх, доданий до відскоку.

   Земля, камінь і динаміт падають з одного удару. Руда має
   міцність (BLOCKS[id].tough) — кірка знімає свій dmg за удар,
   тріщини наростають, очки дає тільки повний розкол.

   Блок-множник множить УЖЕ НАКОПИЧЕНИЙ виграш. Очки, зароблені
   після нього, цим множником не іксуються — тільки наступними.

   ДЕТЕРМІНІЗМ: крок завжди SIM_DT. tick() не приймає dt зовні —
   саме через це сервер і клієнт отримують однакову траєкторію.
   ============================================================ */

import { BLOCKS, CONFIG, SIM_DT, TIERS, tierIndex } from './config';
import type { Rng } from './rng';
import { isWall, Mine, type Cell } from './world';
import type { RunEndReason, RunEvent, Tier, TierId } from './types';

const P = CONFIG.phys;
const clamp = (v: number, a: number, b: number) => (v < a ? a : v > b ? b : v);

/* ---- прибирання шахти ----
   Ряди, які лишились позаду, викидаються, щоб пам'ять не росла.
   Але викинути ряд = ЗАБУТИ його стан: тріщини обнуляться, а розбиті
   блоки повернуться цілими, бо генерація порядкова і відтворить ряд
   з нуля. Тому пруном керує сам рушій, а не той, хто його малює.

   Межа рахується від НАЙВИЩОЇ ЖИВОЇ кірки, а не від найглибшої:
   кірок у забігу може бути кілька, вони розтягуються на десятки рядів,
   і межа за найглибшою зрізала б ряди, в яких відсталі ще копають.
   Саме на цьому клієнт розходився з сервером.

   Для самої ФІЗИКИ вистачило б і десятка рядів: найсильніший підкид
   (вибух TNT) піднімає кірку менш ніж на 2 клітинки, вище вона просто
   не буває.

   Але межу диктує не фізика, а ЕКРАН. Усе, що гравець може побачити,
   мусить лишатись у кеші: викинутий ряд Mine.peek() перерахує з нуля —
   ЦІЛИМИ блоками, і на екрані пробитий тунель «заросте». Дістати вгору
   можна двома способами, і обидва треба покрити:

     - віддалення щипком: при найменшій клітинці над кіркою видно
       до ~38 рядів;
     - гортання поля пальцем: обмежене PAN_LIMIT у презентері, і саме
       звідси воно й береться.

   Звідси 120: із запасом на обидва випадки. Ціна — 120 рядів по 10
   клітинок у пам'яті, тобто дрібниця. На саму симуляцію більший запас
   не впливає ніяк: прун лише чистить кеш, а фізика туди не повертається.
   Експортується, щоб клієнт не вгадував це число, а брав звідси. */
export const PRUNE_MARGIN = 120;
const PRUNE_EVERY = 60;   // кроків між прибираннями

/* TNT: вибух — не статична фігура (квадрат) і не рівномірний розкид по
   ньому, а ПРОМЕНІ з епіцентру в випадкових напрямках (як у Minecraft):
   кожен промінь має свою "потужність", яка гасне по дорозі.

   ЧОМУ РАНІШЕ ВИХОДИЛО ВСЕ ОДНО РІВНЕ КОЛО. Гасіння перекидалось НА
   КОЖНОМУ КРОЦІ, і за сім-вісім кроків ці кидки усереднювались: усі
   промені долітали приблизно однаково далеко. Тобто випадковість була,
   але закон великих чисел з'їдав її саме там, де вона й потрібна.

   Тепер розкид ПО ПРОМЕНЮ, а не по кроку:
     - своє гасіння на весь промінь (TNT_DECAY_MIN/RAND). Промінь із
       малим гасінням пробиває далеко, із великим — глухне поруч, і
       вибух виходить із язиками, а не кулею;
     - промінь ще й ВИЛЯЄ по дорозі (TNT_WOBBLE) — тому край рваний, а
       не циркульний.

   TNT_RAYS — скільки променів пускати; TNT_POWER_MIN/MAX — стартова
   потужність; TNT_STEP — крок у клітинках. Дальність променя ≈
   power / decay * step, тобто зараз від ~1.4 до ~7.6 клітинок за
   промінь, з типовим значенням близько 3.1 (було рівно ~2.1 в усіх
   променів, звідси й рівне коло).

   TNT_MAX_HITS лишається жорсткою стелею (безпека і узгодженість з
   інваріантом у sim/smoke.ts), якщо променів випадково зійшлось
   забагато. Піднято разом із радіусом: на старій стелі більший вибух
   просто обрізався б, і зусилля пішло б у нікуди. */
export const TNT_RAYS = 13;        // 14 -> 9 -> 13
export const TNT_POWER_MIN = 2.1;  // 2.4 -> 1.6 -> 2.4 -> 2.1
export const TNT_POWER_MAX = 4.2;  // 4.4 -> 3.0 -> 5.0 -> 4.2
export const TNT_STEP = 0.4;
/* Гасіння — ОДНЕ НА ВЕСЬ ПРОМІНЬ (див. пояснення вище), не на крок. */
export const TNT_DECAY_MIN = 0.22;
export const TNT_DECAY_RAND = 0.38;
/* На скільки радіан промінь може вильнути за крок. Дає рваний край;
   більше — і промені почнуть закручуватись у спіраль замість летіти. */
export const TNT_WOBBLE = 0.22;
export const TNT_MAX_HITS = 44;    // стеля ТВЕРДИХ блоків на одну детонацію
                                    // (TNT у наборі не ріжеться — див. impact()).
export const TNT_CHAIN_RADIUS = 2; // увесь TNT у цьому радіусі від епіцентру
                                    // детонує гарантовано, поза залежністю від променів

/* Бонус за довжину ланцюга детонацій: що більше TNT здетонувало одним
   вибухом, то більший множник на ВЕСЬ виграш цього вибуху. Береться
   найвищий досяжний поріг. Входить у RTP (симуляція це враховує). */
export const TNT_CHAIN_BONUS: readonly { at: number; mult: number }[] = [
  { at: 3, mult: 1.10 },
  { at: 5, mult: 1.25 },
  { at: 10, mult: 1.50 },
];
export function tntChainBonus(chain: number): number {
  let m = 1;
  for (const b of TNT_CHAIN_BONUS) if (chain >= b.at) m = b.mult;
  return m;
}

/* Блок-множник (x2..x15) БІЛЬШЕ НЕ іксує вже зібране. Замість цього він
   відкриває ВІКНО на MULT_WINDOW_SEC секунд, і все, що зібрано за цей
   час (звичайні удари + вибухи TNT), множиться на активний множник.
   Новий множник під час відкритого вікна: беремо БІЛЬШИЙ із двох
   (не перемножуємо), таймер скидається на повні MULT_WINDOW_SEC.
   Це ЄДИНИЙ множник виграшу в грі: другим був стіл зачарування
   (p.enchantMult), його прибрано разом із самим блоком. */
export const MULT_WINDOW_SEC = 15;

/* ---- ЗРИВ ІЗ ВЕРТИКАЛІ ----
   Кірка охоче звалюється «під себе»: пробила колонку блоків і далі
   падає майже вертикально тим самим тунелем. Гри в цьому мало — поле
   широке, а працює одна вузька смуга.

   Тому лічимо, скільки часу кірка рухається майже без горизонтальної
   складової, і після straightSec зриваємо її з вертикалі. Напрямок —
   туди, куди кірку КРУТИТЬ (а не до центру поля й не випадковий): тіло,
   що втратило рівновагу, падає в бік свого нахилу. Біля стінки вибору
   немає — там однозначно від неї. Випадкова тут лише сила поштовху, і
   береться вона з того самого потоку this.rnd(), тому детермінізм
   клієнт/сервер не страждає.

   ЦЕ СТРАХОВКА, А НЕ ДЖЕРЕЛО РУХУ. Доки відскок був бінарним («збоку /
   зверху») і бічну швидкість давав фіксований sideKick, кірка сідала у
   вертикаль постійно й механізм смикав її щосекунди — звідси й короткі
   straightSec = 0.7 з сильним straightPush = 3.0.

   Тепер вертикаль нестійка сама по собі: центр мас зміщений до
   головки, тому будь-який дотик не строго головкою перекидає кірку, а
   тертя перетворює перекидання на зісковзування (див. resolveContact).
   Тож поріг піднято, а поштовх послаблено — і головне, він тепер
   переважно КРУТИТЬ кірку, а бічну швидкість додає лише як затравку.
   Далі її підхоплює вже звичайна фізика дотику. */

/* ---- ВИШТОВХУВАННЯ З БЛОКУ (див. Run.separate) ----
   Скільки разів за крок повторити розділення. Одного проходу мало:
   вилізши з одного блоку, кірка може впертись у сусідній — у куті
   тунелю таких блоків одразу два. Трьох вистачає з запасом, а ціна
   кожного — той самий перебір 3x3, що й у колізії.

   EPS — нижче цього перекриття вважаємо дотиком і не смикаємо кірку:
   без нього вона щокроку зсувалась би на 1e-15 і без потреби гасила
   швидкість. */
const SEPARATE_PASSES = 3;
const SEPARATE_EPS = 1e-4;

/* Одна кірка — тіло у фізиці */
export class Pick {
  level: number;
  tier: Tier;
  hpMax: number;
  hp: number;
  /* Алмазна кірка (топ-тір): перший верстак лікує ПОВНІСТЮ, кожен
     наступний — лише +CONFIG.workbench.topHeal HP (не понад hpMax). */
  topHealUsed = false;

  x: number;
  y: number;
  vx = 0;
  vy = 0;
  rot = -0.5;
  rotV = 0;

  blocks = 0;
  hits = 0;
  depth = 0;
  dead = false;
  /** скільки секунд поспіль кірка йде майже вертикально (див. STRAIGHT_SEC) */
  straightT = 0;
  /** Поточний розмір кірки: множить і спрайт, і РАДІУС ЗІТКНЕННЯ
      (див. collide). 1 — звичайна; далі CONFIG.grow.scale у степені
      кількості активних збільшень. */
  scale = 1;
  /** Таймери активних збільшень. Кожне живе своє життя (CONFIG.grow.sec),
      тому ефект спадає сходинками, а не зникає весь разом. */
  growT: number[] = [];
  /** скільки ще секунд діє прискорене падіння після гумового блоку */
  rubberT = 0;
  /* Кулдаун — ОКРЕМО НА КОЖНУ клітинку (мапа, не одне останнє значення):
     удар тепер б'є ВСІ дотичні блоки за раз (див. collide()), тому
     "останній дотик" одним ключем більше не описує стан коректно —
     дві різні клітинки, зачеплені в той самий момент, затирали б
     кулдаун одна одної. */
  lastHit = new Map<string, number>();

  constructor(tier: Tier, col: number, y0: number) {
    this.level = tierIndex(tier.id);
    this.tier = tier;
    this.hpMax = tier.hp;
    this.hp = tier.hp;
    this.x = col + 0.5;
    this.y = y0;
  }
}

export interface RunOptions {
  /** з яких колонок стартують кірки — приходить із RoundResult */
  cols: number[];
  /** потік випадковості фізики (окремий від шахти й рулетки) */
  rnd: Rng;
}

export class Run {
  readonly mine: Mine;
  readonly picks: Pick[];
  private readonly rnd: Rng;

  collected = 0;        // спільний рахунок усіх кірок
  multChain = 1;        // найбільший активний множник вікна за забіг (для показу)
  /* Вікно множення від блока-множника (спільне на весь забіг). Поки
     multWindowT > 0, зібране множиться на multActive. */
  multActive = 1;
  multWindowT = 0;
  blocks = 0;
  hits = 0;
  depth = 0;
  upgrades = 0;
  tnts = 0;
  mults = 0;
  /* Скаттери за весь забіг — спільні на всі кірки, а не на кожну свої:
     нагорода одна на раунд. */
  scatters = 0;
  time = 0;
  steps = 0;
  over = false;
  reason: RunEndReason | null = null;
  events: RunEvent[] = [];   // клієнт їх вичитує на партикли/тряску

  private pruneIn = PRUNE_EVERY;

  /* Накопичувачі дотику на ОДИН крок collide(). Поля, а не локальні
     змінні, бо заповнює їх impact() (по клітинці), а використовує
     collide() (один раз на всі клітинки). Інстансні, а не свіжий об'єкт
     на крок: у симуляціях це мільйони кроків, зайвого сміття не треба.

     hitStrength — наскільки пружним має вийти цей дотик за ІГРОВИМИ
     правилами (розбитий блок 1, тріщина crackBounce, верстак 0.7).
     Геометрія (чим ударили, який розмір кірки) домножується окремо в
     collide(). Береться максимум, а не сума: зачепивши три блоки, кірка
     відскакує один раз, найпружнішим із них.
     rubberKick — >0, якщо серед зачеплених була гума; вона задає
     нормальну швидкість напряму й перебиває звичайний відскок.
     rubberNx/rubberNy — напрямок ВІД ГУМИ, накопичений окремо від
     спільної нормалі дотику (навіщо — див. collide). */
  private hitStrength = 0;
  private rubberKick = 0;
  private rubberNx = 0;
  private rubberNy = 0;

  /* У БОНУСЦІ множники СТАКАЮТЬСЯ і не згасають: кожен спійманий ікс
     домножується до активного й діє до кінця забігу. У звичайній грі
     працює вікно на MULT_WINDOW_SEC секунд, де береться більший із
     двох. Ознаку беремо з самої шахти — вона вже знає, що бонусна, і
     тягнути окремий прапорець крізь конструктор не треба. */
  get multPermanent(): boolean { return this.mine.bonus; }

  constructor(tiers: Tier[], mine: Mine, opts: RunOptions) {
    this.mine = mine;
    this.rnd = opts.rnd;
    this.picks = tiers.map((t, i) =>
      new Pick(t, opts.cols[i % opts.cols.length], -P.startHeight));
  }

  get alive(): Pick[] { return this.picks.filter((p) => !p.dead); }

  /* Виплата без стелі — потрібна, щоб знати, чи стеля спрацювала */
  rawPayout(bet: number): number { return Math.round(this.collected * bet / CONFIG.payoutK); }

  payout(bet: number): number { return Math.min(this.rawPayout(bet), bet * CONFIG.maxWinX); }

  /* Стеля зрізала виграш? Тоді UI мусить це сказати, інакше показаний
     множник не сходиться з виплатою і виглядає як обман. */
  isCapped(bet: number): boolean { return this.rawPayout(bet) > bet * CONFIG.maxWinX; }

  /* ---------------- крок симуляції ----------------
     Рівно SIM_DT. Клієнт накопичує реальний час і викликає tick()
     стільки разів, скільки набігло. */
  tick(): void {
    if (this.over) return;
    const dt = SIM_DT;
    this.time += dt;
    this.steps++;

    /* Вікно множника цокає незалежно від того, чи хтось зараз копає.
       У бонусці вікна немає — множник стакнутий назавжди. */
    if (!this.multPermanent && this.multWindowT > 0) {
      this.multWindowT -= dt;
      if (this.multWindowT <= 0) { this.multWindowT = 0; this.multActive = 1; }
    }

    /* Позиція кожної кірки, яка ОБРОБЛЯЛАСЬ цього тіку — жива на вході,
       навіть якщо саме цим кроком і померла. Пруниться нижче по НІЙ, а
       не по «живих зараз»: інакше кірка, що вмирає рівно від удару
       (наприклад, TNT забирає багато HP і саме це вбиває), випадає зі
       списку живих ДО pruneMine() у цьому ж тіку — і якщо інша кірка
       вже глибша за поточну позицію мертвої на PRUNE_MARGIN, ряд із
       щойно згенерованою подією (той-таки TNT) прибирається негайно.
       Клітинка потім регенерується наново (детерміновано, з того самого
       сида) — і на місці порожньої після вибуху клітинки знову
       з'являється блок. Особливо ймовірно тепер, коли TNT рознощить
       значно більше блоків і забіги стали довшими. */
    let touchedTop = Infinity;
    for (const p of this.picks) {
      if (p.dead) continue;
      this.stepPick(p, dt);
      if (p.y < touchedTop) touchedTop = p.y;
      if (this.over) break;
    }

    let deepest = this.depth;
    for (const p of this.picks) if (p.depth > deepest) deepest = p.depth;
    this.depth = deepest;

    if (this.picks.every((p) => p.dead)) this.finish('broken');
    else if (this.time > P.maxTime) this.finish('timeout');

    if (--this.pruneIn <= 0) { this.pruneIn = PRUNE_EVERY; this.pruneMine(touchedTop); }
  }

  /* Викидаємо тільки те, до чого вже точно не дотягнеться жодна жива кірка.
     touchedTop — від tick(): позиції кірок, ОБРОБЛЕНИХ цього тіку (тобто
     тих, чиї події могли щойно потрапити в run.events), а не переобчислення
     «хто живий зараз» — див. коментар у tick(). */
  private pruneMine(touchedTop: number): void {
    if (!Number.isFinite(touchedTop)) return;
    this.mine.prune(Math.floor(touchedTop) - PRUNE_MARGIN);
  }

  /** Догнати забіг до кінця — сервер і симуляції */
  runToEnd(): this {
    let guard = 0;
    while (!this.over && guard++ < P.maxSteps) {
      this.events.length = 0;
      this.tick();
    }
    if (!this.over) this.finish('limit');
    return this;
  }

  private stepPick(p: Pick, dt: number): void {
    /* Кулдаун по клітинці живе рівно hitCooldown секунд: запис, старший
       за це, вже ніколи не пройде перевірку в impact() (this.time тільки
       зростає), тому тримати його немає сенсу. Без чистки мапа росла на
       кожну унікальну зачеплену клітинку за весь забіг — десятки тисяч
       ключів на довгій кірці. Поведінка від цього не змінюється, поріг
       розміру — лише щоб не ходити по мапі щокроку. */
    if (p.lastHit.size > 64) {
      const cutoff = this.time - P.hitCooldown;
      for (const [k, at] of p.lastHit) if (at < cutoff) p.lastHit.delete(k);
    }

    /* Збільшення кірки — незалежні таймери. Кожен тікає сам, і щойно
       якийсь вичерпався, розмір перераховується з тих, що лишились. */
    if (p.growT.length) {
      for (let i = p.growT.length - 1; i >= 0; i--) {
        p.growT[i] -= dt;
        if (p.growT[i] <= 0) p.growT.splice(i, 1);
      }
      p.scale = Math.pow(CONFIG.grow.scale, p.growT.length);
    }

    /* Після гумового блоку кірка не лише сильніше відскакує, а й швидше
       падає — інакше «трамплін» відчувався б як пливкий стрибок у ваті.
       Прискорення й стеля падіння множаться на той самий boost, і рівно
       на fallSec секунд. */
    let gravity = P.gravity;
    let maxFall = P.maxFall;
    if (p.rubberT > 0) {
      p.rubberT = Math.max(0, p.rubberT - dt);
      /* Пришвидшення часу, а не «важча кірка»: швидкості множимо на
         speedUp, прискорення — на його КВАДРАТ. Інакше дуга не
         прискорилась би, а просто стала нижчою. */
      const sp = CONFIG.rubber.speedUp;
      gravity *= sp * sp;
      maxFall *= sp;
    }

    p.vy = Math.min(maxFall, p.vy + gravity * dt);
    p.vx -= p.vx * P.airDrag * dt;

    /* Довго падає майже прямо вниз — штовхаємо вбік, до центру поля.
       Див. коментар біля STRAIGHT_SEC. */
    if (Math.abs(p.vx) < P.straightVx) {
      p.straightT += dt;
      if (p.straightT >= P.straightSec) {
        p.straightT = 0;
        /* КУДИ штовхати. Раніше — завжди до центру поля, і саме це
           тримало кірку у вузькій смузі: щойно вона відходила вбік і
           починала падати прямо, той самий механізм повертав її назад.
           Виходив магніт у центр, а не ширший хід.

           Тепер напрямок беремо з САМОЇ КІРКИ: вона звалюється туди,
           куди її крутить (знак rotV) — так падає будь-яке тіло, яке
           втратило рівновагу, і на екрані це читається як продовження
           видимого кувирка, а не ривок нізвідки. Центр більше нікого не
           притягує; стінка ж лишається межею — за WALL_GUARD від неї
           напрямок однозначно «від стінки». */
        const nearLeft = p.x < P.wallGuard;
        const nearRight = p.x > this.mine.cols - P.wallGuard;
        const atWall = nearLeft || nearRight;
        const dir = nearLeft ? 1
          : nearRight ? -1
          : Math.abs(p.rotV) > 1e-3 ? Math.sign(p.rotV)
          : (this.rnd() < 0.5 ? -1 : 1);
        /* Біля стінки штовхаємо сильніше (wallEscape): звичайного
           поштовху там не вистачає, щоб вийти з крайньої смуги, і кірка
           лишалась висіти на місці, лише щосекунди смикаючись. */
        const push = P.straightPush * (atWall ? P.wallEscape : 1);
        p.vx = clamp(p.vx + dir * push * (0.6 + this.rnd() * 0.8),
                     -P.maxSideSpeed, P.maxSideSpeed);
        /* Крутимо сильніше, ніж штовхаємо: далі кірку понесе вбік уже
           тертя на першому ж дотику, і рух вийде наслідком видимого
           кувирка, а не ривком нізвідки. Ручка своя (straightSpin), а не
           spinKick: той самий spinKick відповідає ще й за розкрут від
           вибуху TNT, і тягнути їх одним числом означало б міняти вибух
           щоразу, коли підбираєш поведінку падіння. */
        p.rotV = clamp(p.rotV + dir * P.straightSpin, -P.maxSpin, P.maxSpin);
      }
    } else {
      p.straightT = 0;
    }
    /* Оберт — ЧАСТИНА ФІЗИКИ, а не анімація: з нього беруться і напрямок
       головки, і положення центра мас, тобто і сила відскоку, і момент
       від удару (див. resolveContact). Модель — маятник: важча головка
       тягне кірку в положення restRot («головкою вниз»). Слабка пружина
       (rotPull) + гасіння (spinDamp) + стеля (maxSpin) -> кірку від
       удару гойдає, і вона плавно влягається, а не завмирає під
       випадковим кутом і не крутиться дзиґою. */
    const TAU = Math.PI * 2;
    let d = (p.rot - P.restRot) % TAU;
    if (d > Math.PI) d -= TAU; else if (d < -Math.PI) d += TAU;
    p.rotV -= d * P.rotPull * dt;
    p.rotV = clamp(p.rotV - p.rotV * P.spinDamp * dt, -P.maxSpin, P.maxSpin);
    p.rot += p.rotV * dt;

    const dist = Math.hypot(p.vx, p.vy) * dt;
    const n = Math.max(1, Math.ceil(dist / P.substep));
    const sdt = dt / n;

    for (let i = 0; i < n && !p.dead; i++) {
      p.x += p.vx * sdt;
      p.y += p.vy * sdt;
      this.collide(p);
    }
    if (p.y > p.depth) p.depth = p.y;
  }

  private collide(p: Pick): void {
    // радіус росте разом із кіркою (блок-стрілка), інакше «більша кірка»
    // була б суто картинкою і нічого не міняла в грі
    const R = P.bodyR * p.scale;

    /* Бічні стінки шахти — той самий розв'язувач дотику, лише з іншою
       пружністю і без поштовху врубання (стінку не довбають). Раніше
       тут просто перевертався знак vx, і кірка з'їжджала вздовж стінки
       з незмінною вертикальною швидкістю, ніби та ідеально слизька.
       Тепер об стінку працює й тертя, й обертання — кірка від неї
       відштовхується вбік ТА гальмує падіння, як і має. */
    if (p.x < R) {
      p.x = R;
      if (p.vx < 0) this.resolveContact(p, R, 1, 0, P.wallBounce, P.wallKick, P.maxRise);
    } else if (p.x > this.mine.cols - R) {
      p.x = this.mine.cols - R;
      if (p.vx > 0) this.resolveContact(p, R, -1, 0, P.wallBounce, P.wallKick, P.maxRise);
    }

    /* Колізія — не одна точка попереду по вектору швидкості (тоді
       ручка, що стирчить збоку чи позаду напрямку польоту, могла
       пройти крізь блок без дотику), а все тіло кірки: коло радіусом R
       навколо центру. Перевіряємо всі клітинки в вікні навколо центру —
       і б'ємо УСІ, чия найближча точка ближче за R, ОДНОЧАСНО за цей
       крок, а не лише найближчу: якщо кірка (чи її ручка) одразу
       торкається кількох блоків, усі мають отримати удар разом.
       Порядок ітерації фіксований (rr потім cc за зростанням) — тому
       детермінізм між клієнтом і сервером не ламається. */
    /* Вікно перебору — від радіуса, а не фіксовані 3x3: збільшена кірка
       дістає далі, ніж на одну клітинку, і при жорсткому 3x3 половина
       її тіла проходила б крізь блоки без дотику. */

    /* ОДИН ДОТИК — ОДИН ВІДСКОК.
       Удари (урон, очки, події) лишаються ПОКЛІТИННИМИ: скільки граней
       зачепили, стільки блоків і отримає своє. А от відскок тепер
       рахується РАЗ на крок, по сумарній нормалі.

       Досі кожна зачеплена клітинка кидала кірку окремо. У куті тунелю
       їх одразу дві-три, кожна додавала свій бічний поштовх у СВІЙ бік,
       і виживав просто останній за порядком перебору — кірку жбурляло в
       напрямок, який не відповідав жодній реальній грані. Саме звідси
       бралися ті ривки, що виглядали як випадкові.

       Нормалі складаємо з вагою за глибиною проникнення й нормуємо:
       підлога + стінка дають чесні 45°, і кірка вилітає з кута по
       бісектрисі — так, як вона туди й зайшла. */
    this.hitStrength = 0;
    this.rubberKick = 0;
    this.rubberNx = 0;
    this.rubberNy = 0;
    let sumX = 0, sumY = 0;

    const cx = Math.floor(p.x), cy = Math.floor(p.y);
    const reach = Math.ceil(R);
    for (let rr = cy - reach; rr <= cy + reach && !p.dead; rr++) {
      for (let cc = cx - reach; cc <= cx + reach && !p.dead; cc++) {
        const cell = this.mine.get(rr, cc);
        if (!cell || isWall(cell)) continue;
        const qx = clamp(p.x, cc, cc + 1);
        const qy = clamp(p.y, rr, rr + 1);
        const dx = p.x - qx, dy = p.y - qy;
        const d = Math.hypot(dx, dy);
        if (d >= R) continue;

        const w = R - d;                     // глибина проникнення — вага нормалі
        if (d > 1e-6) {
          sumX += (dx / d) * w;
          sumY += (dy / d) * w;
        } else {
          /* Центр кірки ВСЕРЕДИНІ клітинки — напрямку «назовні» з
             геометрії не дістати. Беремо найближчу грань, як і
             separate(), щоб обидва місця виводили кірку однаково. */
          const l = p.x - cc, rgt = cc + 1 - p.x, u = p.y - rr, b = rr + 1 - p.y;
          const m = Math.min(l, rgt, u, b);
          if (m === l) sumX -= w;
          else if (m === rgt) sumX += w;
          else if (m === u) sumY -= w;
          else sumY += w;
        }

        this.impact(p, rr, cc, cell);
      }
    }

    /* Відскок — після ВСІХ ударів: impact() лише накопичує, наскільки
       пружним має вийти дотик (hitStrength), або повідомляє, що серед
       зачеплених була гума (rubberKick). Мертвій кірці відскакувати
       нічим. */
    if (!p.dead) {
      if (this.rubberKick > 0) {
        /* ТРАМПЛІН ШТОВХАЄ ВІД СЕБЕ, А НЕ ВІД СЕРЕДНЬОГО ДОТИКУ.

           Спільна нормаль (sumX/sumY) усереднює ВСІ зачеплені клітинки.
           Для слайма це неправильно двічі: у тунелі бічні грані тягнуть
           напрямок убік, а якщо кірка затиснута між блоками, нормалі
           взагалі гасять одна одну (len ≈ 0) — і стрибка не було б
           зовсім, хоча гравець бачив дотик до слайма. Тому в гуми своя
           нормаль, зібрана лише з її власних клітинок.

           Виродженого випадку не лишаємо: якщо й вона не визначилась
           (кірка центром усередині слайма), кидаємо вгору — трамплін
           мусить спрацювати завжди. */
        const rl = Math.hypot(this.rubberNx, this.rubberNy);
        const nx = rl > 1e-6 ? this.rubberNx / rl : 0;
        const ny = rl > 1e-6 ? this.rubberNy / rl : -1;
        /* Нормальну швидкість ЗАДАЄМО (тому rest = 0), стелі підйому
           немає — це трамплін, а не відскок від блока. */
        this.resolveContact(p, R, nx, ny, 0, this.rubberKick * this.hitBounce(p, nx, ny),
                            Infinity, P.maxSideSpeed * CONFIG.rubber.sideBoost);
      } else {
        const len = Math.hypot(sumX, sumY);
        if (len > 1e-6 && this.hitStrength > 0) {
          const nx = sumX / len, ny = sumY / len;
          const s = this.hitBounce(p, nx, ny) * this.hitStrength;
          this.resolveContact(p, R, nx, ny, P.restitution * s, P.bounceKick * s, P.maxRise);
        }
      }
    }

    this.separate(p, R);
  }

  /* ---- РОЗВ'ЯЗАННЯ ДОТИКУ ----

     Замість гілки «збоку / зверху» — нормальний імпульс по РЕАЛЬНІЙ
     нормалі грані. Стара схема мала дві вади, і обидві були видні на
     екрані. По-перше, розрив: удар під 44° і під 46° давали зовсім різну
     поведінку, бо `sideways` — булеве. По-друге, бічний поштовх брався
     від напрямку на ЦЕНТР БЛОКУ, а не від точки дотику, тож зачепивши
     кут блоку, центр якого правіше, кірка летіла вліво на повну.

     Швидкість розкладаємо на нормаль n (від грані до центра кірки) і
     дотичну t. Далі — три незалежні речі:

       1. НОРМАЛЬ. Гаситься й відбивається лише те, що йшло В поверхню.
          Якщо кірка вже відлітає — не чіпаємо: додавати імпульс тілу,
          яке й так віддаляється, немає з чого.

       2. ДОТИЧНА (тертя). Кулонова межа: |jt| <= friction * |jn|. Легкий
          дотик майже не тримає, важкий — тримає добре. Гаситься не
          швидкість ЦЕНТРА, а швидкість МАТЕРІАЛЬНОЇ ТОЧКИ дотику, у яку
          входить і обертання.

       3. МОМЕНТ. Центр мас зміщений до головки на comOffset, тому плече
          від нього до точки дотику ненульове, і навіть чисто нормальний
          імпульс перекидає кірку, щойно вона зустріла грань не строго
          головкою. Тертя дає другу половину моменту.

     Звідки береться ДІАГОНАЛЬ. Швидкість точки дотику вздовж грані:

         vt_точки = vt + rotV * (r·n)

     (плече r·n від'ємне — точка дотику лежить з боку грані). Тобто
     кірка, що крутиться, ковзає по грані навіть падаючи прямовисно —
     і тертя перетворює це ковзання на бічний рух центра, а віддача
     моменту гальмує сам оберт. Обмін іде в обидва боки: розігнану вбік
     кірку наступний дотик пригальмує й перетворить бічну швидкість
     назад в обертання.

     Це і є та різниця, заради якої все переписано. Старий sideKick був
     ДОДАВАННЯМ енергії з нічого й у той самий бік — чим більше кірка
     стукалась, тим сильніше її розганяло. Тертя ж енергію ЗАБИРАЄ, тому
     бічний рух самообмежний: кірку більше не носить, вона зісковзує
     рівно настільки, наскільки її перед цим крутнуло. І гравець це
     бачить — кувирок на екрані й є причина зносу.

     ДЕТЕРМІНІЗМ: жодного this.rnd() тут немає взагалі. Відскок повністю
     визначається станом кірки й геометрією грані. */
  private resolveContact(p: Pick, R: number, nx: number, ny: number,
                         rest: number, kick: number, rise: number,
                         // явний number: CONFIG оголошений as const, тож
                         // без анотації тип звузився б до літерала 10
                         sideCap: number = P.maxSideSpeed): void {
    const tx = -ny, ty = nx;
    const vn = p.vx * nx + p.vy * ny;   // <0 — йдемо В поверхню
    const vt = p.vx * tx + p.vy * ty;

    /* Куди дивиться головка. За побудовою при rot = restRot вона
       дивиться ВНИЗ, тобто в бік (0, +1) — звідси стала поправка. */
    const head = p.rot - P.restRot + Math.PI / 2;
    const hx = Math.cos(head), hy = Math.sin(head);

    /* Плече від ЦЕНТРА МАС до точки дотику. Точка дотику — на грані,
       тобто на -R по нормалі від геометричного центра; центр мас —
       на +comOffset у бік головки. */
    const com = P.comOffset * p.scale;
    const rx = -R * nx - com * hx;
    const ry = -R * ny - com * hy;
    const lever = rx * nx + ry * ny;          // r·n, від'ємне

    // швидкість точки дотику вздовж грані: центр + внесок обертання
    const slide = vt + p.rotV * lever;

    /* Нормальна складова. Поштовх врубання ніколи не ДОДАЄТЬСЯ до вже
       наявного відльоту — лише підтягує його до себе, інакше кілька
       дотиків підряд знову накачували б кірку енергією. */
    const vnOut = vn < 0 ? -vn * rest + kick : Math.max(vn, kick);
    const jn = vnOut - vn;

    // тертя: скільки ковзання можемо забрати, і скільки нам дозволено
    const jtMax = Math.abs(jn) * P.friction;
    const jt = clamp(-slide * P.grip, -jtMax, jtMax);

    p.vx = vnOut * nx + (vt + jt) * tx;
    p.vy = vnOut * ny + (vt + jt) * ty;
    if (p.vy < -rise) p.vy = -rise;
    /* Стеля бічної швидкості. Для трампліна вона піднята (sideCap):
       інакше слайм, у який влетіли збоку, штовхав би кірку по нормалі
       сильно, а на екрані вона впиралась би в ту саму межу, що й від
       звичайного дотику — сильний відскок було б видно лише вгору. */
    p.vx = clamp(p.vx, -sideCap, sideCap);

    /* Момент = r x J. Нормальна частина дає момент лише через зміщення
       центра мас (r x n = -com * (h x n)), дотична — через усе плече. */
    const torque = jn * (rx * ny - ry * nx) + jt * lever;
    p.rotV = clamp(p.rotV + torque * P.spinInertia, -P.maxSpin, P.maxSpin);
  }

  /* ВИШТОВХУВАННЯ З БЛОКУ.

     Колізія вище міняє лише ШВИДКІСТЬ — позицію вона не чіпала ніколи.
     Через це кірка спокійно заїжджала тілом у блок, який пережив удар:
     на екрані спрайт наполовину в текстурі, а гра вважає, що все гаразд.
     З crackBounce (слабкий відскок від цілого блоку) це стало видно
     постійно — саме тому виштовхування й додано.

     Рахуємо як звичайне розділення кола й прямокутника: беремо
     НАЙГЛИБШЕ проникнення й зсуваємо кірку по нормалі рівно настільки,
     щоб дотик став дотиком, а не перекриттям. Кілька проходів — бо,
     вилізши з одного блоку, можна впертись у сусідній (кут тунелю).

     ДЕТЕРМІНІЗМ: жодного this.rnd() тут немає, порядок перебору
     фіксований (rr, потім cc за зростанням), тож клієнт і сервер
     рахують те саме. Але траєкторії це МІНЯЄ — потрібен новий прогін
     балансу. */
  private separate(p: Pick, R: number): void {
    for (let pass = 0; pass < SEPARATE_PASSES; pass++) {
      const cx = Math.floor(p.x), cy = Math.floor(p.y);
      const reach = Math.ceil(R);
      let bestDepth = 0, bestX = 0, bestY = 0;

      for (let rr = cy - reach; rr <= cy + reach; rr++) {
        for (let cc = cx - reach; cc <= cx + reach; cc++) {
          const cell = this.mine.get(rr, cc);
          if (!cell) continue;                 // порожньо — крізь неї й летимо
          const nx = clamp(p.x, cc, cc + 1);
          const ny = clamp(p.y, rr, rr + 1);
          let dx = p.x - nx, dy = p.y - ny;
          let d = Math.hypot(dx, dy);
          if (d >= R) continue;

          if (d < 1e-6) {
            /* Центр кірки ВСЕРЕДИНІ клітинки — напрямку «назовні»
               немає. Виходимо через найближчу грань: так кірка не
               вистрибує через півблоку в довільний бік. */
            const l = p.x - cc, r = cc + 1 - p.x, u = p.y - rr, b = rr + 1 - p.y;
            const m = Math.min(l, r, u, b);
            if (m === l) { dx = -1; dy = 0; d = 0; }
            else if (m === r) { dx = 1; dy = 0; d = 0; }
            else if (m === u) { dx = 0; dy = -1; d = 0; }
            else { dx = 0; dy = 1; d = 0; }
            const depth = R + m;
            if (depth > bestDepth) { bestDepth = depth; bestX = dx; bestY = dy; }
            continue;
          }

          const depth = R - d;
          if (depth > bestDepth) { bestDepth = depth; bestX = dx / d; bestY = dy / d; }
        }
      }

      if (bestDepth <= SEPARATE_EPS) return;   // ніде не перекриваємось
      p.x += bestX * bestDepth;
      p.y += bestY * bestDepth;
      /* Виштовхування з блоку може підштовхнути кірку ЗА бічну стінку
         шахти — обмеження ширини стоїть на початку collide(), тобто
         ДО нас. Тому межу тримаємо тут-таки: інакше кірка виїжджає за
         край поля на ті самі кілька тисячних, і це ловить smoke-тест. */
      p.x = clamp(p.x, R, this.mine.cols - R);
      /* Гасимо швидкість, спрямовану В блок: інакше наступний крок
         інтегрування заганяє кірку назад, і вона тремтить на грані. */
      const into = p.vx * bestX + p.vy * bestY;
      if (into < 0) { p.vx -= into * bestX; p.vy -= into * bestY; }
    }
  }

  private impact(p: Pick, r: number, c: number, cell: Cell): void {
    // не даємо зарахувати кілька ударів по ОДНІЙ й ТІЙ САМІЙ клітинці за мить
    const key = r + ',' + c;
    const last = p.lastHit.get(key);
    if (last !== undefined && this.time - last < P.hitCooldown) return;
    p.lastHit.set(key, this.time);

    const def = BLOCKS[cell.id];
    const idx = this.picks.indexOf(p);
    const dx = p.x - (c + 0.5);
    const dy = p.y - (r + 0.5);
    const sideways = Math.abs(dx) > Math.abs(dy);

    if (def.kind === 'upgrade') {
      this.mine.clear(r, c);
      /* Дотик коштує HP і рахується як удар — так само, як по будь-якому
         іншому блоку (BLOCKS.magic.cost). Раніше ці дві гілки мовчки
         обходили і hp, і hits, тобто поле cost для них було мертвим, а
         конфіг описував поведінку, якої не було. На баланс це майже не
         впливає: одразу нижче кірка все одно лікується до максимуму. */
      p.hp -= def.cost;
      p.hits++; this.hits++;
      /* Верстак: прямий дотик підвищує тір (поки є куди рости) і лікує
         до максимуму. На топ-тірі (Diamond) 1-й верстак дає повний хіл,
         кожен наступний — лише +CONFIG.workbench.topHeal HP (не понад
         hpMax). Довжину забігу тримає HP кірки, а не таймер.
         Вибух TNT сюди не заходить (ламає як звичайний блок). */
      if (p.level < TIERS.length - 1) {
        p.level++;
        p.tier = TIERS[p.level];
        p.hpMax = p.tier.hp;
        p.hp = p.tier.hp;
        this.upgrades++;
        this.events.push({ t: 'upgrade', r, c, tier: p.tier.id as TierId,
                           healOnly: false, topUp: 0, pick: idx });
      } else {
        let topUp = 0;
        if (!p.topHealUsed) { p.hp = p.hpMax; p.topHealUsed = true; }
        else { topUp = Math.min(CONFIG.workbench.topHeal, p.hpMax - p.hp); p.hp += topUp; }
        this.upgrades++;
        this.events.push({ t: 'upgrade', r, c, tier: p.tier.id as TierId,
                           healOnly: true, topUp, pick: idx });
      }
      this.hitStrength = Math.max(this.hitStrength, 0.7);
      this.checkDead(p, idx);
      return;
    }

    /* СТРІЛКА ВГОРУ: кірка більшає в CONFIG.grow.scale разів.
       Разом зі спрайтом росте радіус зіткнення (див. collide), тому за
       крок вона зачіпає площу приблизно в scale² разів більшу. Через це
       ж множимо запас HP: інакше кожен дотик коштує 1 HP, дотиків стає
       вдев'ятеро більше, і «буф» убивав би кірку за частку секунди.
       Не стакається: другий такий блок ламається без ефекту. */
    if (def.kind === 'grow') {
      this.mine.clear(r, c);
      p.hp -= def.cost;
      p.hits++; this.hits++;

      /* Стакається: нове збільшення додає СВІЙ таймер, а розміри
         перемножуються. Запас HP не чіпаємо навмисно — саме він, а не
         радіус, визначає віддачу забігу (див. коментар у CONFIG.grow). */
      if (p.growT.length < CONFIG.grow.maxStacks) {
        p.growT.push(CONFIG.grow.sec);
        p.scale = Math.pow(CONFIG.grow.scale, p.growT.length);
        this.upgrades++;
      }
      this.events.push({ t: 'grow', r, c, scale: p.scale,
                         stacks: p.growT.length, secs: CONFIG.grow.sec, pick: idx });
      this.hitStrength = Math.max(this.hitStrength, 0.7);
      this.checkDead(p, idx);
      return;
    }

    /* СКАТТЕР: грошей не дає, але три за забіг відкривають безкоштовну
       бонуску (CONFIG.scatter.need). Ламається як звичайний блок і так
       само коштує HP — просто замість очок додає одиницю до лічильника.

       Лічильник навмисно не зупиняється на need: зайві скаттери нічого
       не додають, але й обривати підрахунок посеред забігу нема сенсу —
       підсумок має чесно казати, скільки їх було. */
    if (def.kind === 'scatter') {
      this.mine.clear(r, c);
      p.hp -= def.cost;
      p.hits++; this.hits++;
      this.scatters++;
      this.events.push({ t: 'scatter', r, c, n: this.scatters,
                         need: CONFIG.scatter.need, pick: idx });
      this.hitStrength = Math.max(this.hitStrength, 1);
      this.checkDead(p, idx);
      return;
    }

    /* ГУМА: трамплін. Відскок сильніший за звичайний на CONFIG.rubber.boost
       (і вгору, і вбік — разом зі стелею maxRise, інакше приріст просто
       зрізало б нею), а наступні fallSec секунд кірка симетрично швидше
       падає — див. stepPick(). */
    if (def.kind === 'rubber') {
      /* НЕ ламається — блок лишається в шахті. Тому й this.mine.clear()
         тут немає, і cost у нього 0: дотик безкоштовний. Удар усе одно
         рахуємо, щоб страховка maxHits покривала й нескінченне
         стрибання по слайму. */
      p.hits++; this.hits++;
      p.rubberT = CONFIG.rubber.fallSec;
      this.events.push({ t: 'rubber', r, c, secs: CONFIG.rubber.fallSec, pick: idx });

      /* Гума не «додає пружності», а ЗАДАЄ швидкість відльоту, тому
         йде не в hitStrength, а в окремий rubberKick: collide()
         відштовхує по нормалі дотику (rest = 0, без стелі підйому) і
         тим перебиває звичайний відскок.

         Вертикальна складова тепер береться з самої нормалі. Раніше
         vx/vy розкладались тут вручну, і при ударі збоку стрибка не
         виходило зовсім — був напис «ОТСКОК» без стрибка.

         Сила береться від ШВИДКОСТІ УДАРУ, як у слизі в майнкрафті:
         частка restitution від того, з чим прилетіли, у межах
         minKick..maxKick. Раніше імпульс був константою, і легкий
         дотик підкидав рівно так само, як падіння з висоти.

         Невеликий розкид потрібен, бо блок незламний: за строго
         однакового імпульсу кірка зайшла б у ідеальний цикл і стрибала
         б на місці. Випадковість — із того самого потоку rnd().

         Геометрію удару (головкою чи ручкою, який розмір кірки) тут НЕ
         рахуємо: нормаль дотику відома лише в collide(), він і
         домножить на hitBounce. */
      const R = CONFIG.rubber;
      const hitSpeed = Math.abs(sideways ? p.vx : p.vy);
      this.rubberKick = Math.max(this.rubberKick,
        clamp(hitSpeed * R.restitution, R.minKick, R.maxKick)
        * R.speedUp * (0.9 + this.rnd() * 0.2));

      /* Напрямок ВІД ЦЬОГО слайма — окремо від спільної нормалі дотику
         (див. collide). Кілька слаймів за раз складаються, бо штовхають
         з різних боків, і сумарний напрямок — саме те, що треба. */
      const rd = Math.hypot(dx, dy);
      if (rd > 1e-6) { this.rubberNx += dx / rd; this.rubberNy += dy / rd; }

      this.checkDead(p, idx);
      return;
    }

    if (def.kind === 'mult') {
      this.mine.clear(r, c);
      const m = cell.m || 2;
      p.hp -= def.cost;
      p.hits++; this.hits++;
      this.mults++;
      /* Звичайна гра: не іксуємо вже зібране, а відкриваємо/подовжуємо
         вікно. Активний множник = більший із двох (НЕ перемножуємо),
         таймер — на повні MULT_WINDOW_SEC.

         Бонуска: вікна немає взагалі, номінали СКЛАДАЮТЬСЯ і діють до
         кінця забігу — x2, потім x3, потім x10 дають x15, а не x60.
         Перший спійманий блок задає множник рівно своїм номіналом, тож
         стартова одиниця (яка означає «множника ще нема») у суму не
         входить. secs: 0 у події означає «без таймера», клієнт малює
         такий множник без смужки часу. */
      let secs = MULT_WINDOW_SEC;
      if (this.multPermanent) {
        const base = this.multActive <= 1 ? 0 : this.multActive;
        this.multActive = Math.min(CONFIG.buy.multCap, base + m);
        secs = 0;
      } else {
        this.multActive = Math.max(this.multActive, m);
        this.multWindowT = MULT_WINDOW_SEC;
      }
      if (this.multActive > this.multChain) this.multChain = this.multActive;
      this.events.push({ t: 'mult', r, c, m, active: this.multActive, secs, pick: idx });
      this.hitStrength = Math.max(this.hitStrength, 1);
      this.checkDead(p, idx);
      return;
    }

    if (def.kind === 'tnt') {
      this.mine.clear(r, c);
      p.hp -= def.cost;
      p.hits++; this.hits++;

      /* Вибух — ПРОМЕНІ з епіцентру в випадкових напрямках (як у Minecraft),
         не статична фігура і не рівномірний розкид по квадрату. Кожен
         промінь летить, доки не згасне його потужність, руйнуючи тверді
         блоки й верстаки по дорозі — форма виходить органічною випуклістю,
         щоразу іншою.
         ЛАНЦЮГОВА ДЕТОНАЦІЯ: якщо промінь зачепив інший TNT, той теж
         вибухає — від СВОЄЇ позиції, своїми променями, і так само може
         зачепити наступний. `cleared` — спільний набір уже знищених
         клітинок на весь ланцюг (щоб один блок не порахувався двічі
         й пізніший вибух не бив по вже порожньому місцю), `queue` —
         черга позицій, які ще мають вибухнути. chainGuard — запобіжник
         від нескінченного ланцюга в дуже щільному TNT-регіоні.
         Верстак у вибуху ЛАМАЄТЬСЯ (як і просили), але апгрейд і повне
         відновлення HP дає лише ПРЯМИЙ дотик кірки (магічна гілка вище) —
         інакше кірка в бонусці ставала практично безсмертною.
         Детермінізм не ламається: увесь випадок — з того самого потоку
         фізики this.rnd(), клієнт відтворює рівно ту саму форму. */
      const cleared = new Set<string>([r + ',' + c]);
      const queue: [number, number][] = [[r, c]];
      let chainGuard = 0;
      let chainLen = 0;   // скільки TNT здетонувало цим одним вибухом
      let blastGot = 0;   // сирий виграш вибуху до бонуса за ланцюг

      while (queue.length && chainGuard++ < 60) {
        const [er, ec] = queue.shift()!;
        this.tnts++;
        chainLen++;

        const hitMap = new Map<string, { r: number; c: number; id: Cell['id'] }>();
        for (let i = 0; i < TNT_RAYS; i++) {
          let angle = this.rnd() * Math.PI * 2;
          let power = TNT_POWER_MIN + this.rnd() * (TNT_POWER_MAX - TNT_POWER_MIN);
          /* Одне гасіння на весь промінь — саме воно й робить форму
             нерівною (див. коментар до констант). */
          const decay = TNT_DECAY_MIN + this.rnd() * TNT_DECAY_RAND;
          let x = ec + 0.5, y = er + 0.5;
          while (power > 0) {
            angle += (this.rnd() - 0.5) * TNT_WOBBLE;
            x += Math.cos(angle) * TNT_STEP;
            y += Math.sin(angle) * TNT_STEP;
            power -= decay;
            const rr = Math.floor(y), cc = Math.floor(x);
            const key = rr + ',' + cc;
            if (cleared.has(key) || hitMap.has(key)) continue;
            const b = this.mine.get(rr, cc);
            if (!b || isWall(b)) continue;
            const k = BLOCKS[b.id].kind;
            if (k !== 'solid' && k !== 'upgrade' && k !== 'tnt') continue;
            hitMap.set(key, { r: rr, c: cc, id: b.id });
          }
        }

        /* ГАРАНТОВАНА ланцюгова детонація: увесь TNT у радіусі
           TNT_CHAIN_RADIUS від епіцентру вибухає завжди, навіть якщо
           жоден промінь через нього не пройшов. Раніше саме через це
           сусідній динаміт «раз так, раз ні». Детерміновано (без rnd). */
        for (let rr = er - TNT_CHAIN_RADIUS; rr <= er + TNT_CHAIN_RADIUS; rr++) {
          for (let cc = ec - TNT_CHAIN_RADIUS; cc <= ec + TNT_CHAIN_RADIUS; cc++) {
            const key = rr + ',' + cc;
            if (cleared.has(key) || hitMap.has(key)) continue;
            const b = this.mine.get(rr, cc);
            if (b && !isWall(b) && BLOCKS[b.id].kind === 'tnt') {
              hitMap.set(key, { r: rr, c: cc, id: b.id });
            }
          }
        }

        /* TNT з набору НІКОЛИ не відкидається лімітом — інакше ланцюг
           знову рветься. Обрізаємо (за потреби) лише тверді блоки. */
        const all = Array.from(hitMap.values());
        const tntCells = all.filter((b) => BLOCKS[b.id].kind === 'tnt');
        let solidCells = all.filter((b) => BLOCKS[b.id].kind !== 'tnt');
        if (solidCells.length > TNT_MAX_HITS) {
          for (let i = solidCells.length - 1; i > 0; i--) {
            const j = Math.floor(this.rnd() * (i + 1));
            const tmp = solidCells[i]; solidCells[i] = solidCells[j]; solidCells[j] = tmp;
          }
          solidCells = solidCells.slice(0, TNT_MAX_HITS);
        }
        const candidates = [...tntCells, ...solidCells];

        const hit: { r: number; c: number; id: Cell['id'] }[] = [];
        let got = 0;
        for (const b of candidates) {
          cleared.add(b.r + ',' + b.c);
          this.mine.clear(b.r, b.c);                       // вибух розносить одразу, без ударів
          hit.push(b);
          this.blocks++; p.blocks++;
          if (BLOCKS[b.id].kind === 'tnt') queue.push([b.r, b.c]);
          // верстак: value 0, просто ламається. multActive=1 поза вікном.
          else got += BLOCKS[b.id].value * this.multActive;
        }
        blastGot += got;

        this.events.push({ t: 'tnt', r: er, c: ec, hit, got, chain: chainLen, pick: idx });
      }

      /* Бонус за довжину ланцюга — на ВЕСЬ виграш цього вибуху. */
      const chainMult = tntChainBonus(chainLen);
      this.collected += blastGot * chainMult;
      if (chainMult > 1) {
        this.events.push({ t: 'tntchain', r, c, chain: chainLen, mult: chainMult,
                           extra: blastGot * (chainMult - 1), pick: idx });
      }

      /* ВІДКИД ВІД ВИБУХУ — від епіцентру, а не завжди строго вгору:
         видно, з якого боку рвонуло, і кірку зносить убік, а не лише
         підкидає. Що ближче епіцентр до положення «під кіркою», то
         сильніший підкид.

         Вертикальну складову ЗАДАЄМО, а не додаємо. Кірка часто входить
         у динаміт на повній швидкості падіння (maxFall), і доданий
         імпульс просто потонув би в ній — саме тому старий підкид
         (жорстко вгору, 6.0) піднімав менш ніж на клітинку й на екрані
         не читався зовсім. Стеля maxRise сюди навмисно не діє: це вибух,
         а не відскок від блока. */
      const ex = p.x - (c + 0.5);
      const ey = p.y - (r + 0.5);
      const len = Math.hypot(ex, ey) || 1;
      const fromBelow = Math.max(0, -ey / len);   // 1 — рвонуло рівно під кіркою

      p.vy = -P.tntBlast * (0.6 + 0.4 * fromBelow);
      /* Вибух кидає різко — це його робота, тому йому дозволено
         перевищити стелю звичайного руху (див. tntSide у config). */
      const tntCap = P.maxSideSpeed * P.tntSide;
      p.vx = clamp(
        p.vx * 0.35 + (ex / len) * P.tntBlast * 0.7 + (this.rnd() - 0.5) * P.tntBlast * 0.35,
        -tntCap, tntCap,
      );
      p.rotV += (this.rnd() < 0.5 ? -1 : 1) * P.spinKick * 1.2;
      this.checkDead(p, idx);
      return;
    }

    /* звичайний блок: кірка знімає свій урон.
       Земля/камінь мають tough 1 — падають з першого удару будь-якою кіркою.
       Руда міцніша, і чим краща кірка, тим менше ударів на неї треба. */
    p.hp -= def.cost;
    p.hits++; this.hits++;
    cell.dmg += p.tier.dmg;

    const broke = cell.dmg >= def.tough;
    if (broke) {
      this.mine.clear(r, c);
      const got = def.value * this.multActive;
      this.collected += got;
      this.blocks++; p.blocks++;
      this.events.push({ t: 'break', r, c, id: def.id, got, pick: idx });
    } else {
      this.events.push({ t: 'crack', r, c, id: def.id, stage: cell.dmg, of: def.tough, pick: idx });
    }

    /* Блок вистояв і лежить ПІД кіркою — вона майже не відскакує
       (P.crackBounce), тобто прогризає жилу, а не стрибає від неї.

       Саме «під» тут суттєве, і це не те саме, що просто «вистояв».
       Глушити будь-який невдалий удар означало б гасити й ті, де кірка
       влетіла в стінку жили ЗБОКУ: там відскок якраз потрібен, інакше
       вона зависає в повітрі біля вертикальної грані й довбає її, ніби
       приклеєна. Вниз вона впирається у власну вагу — і це виглядає як
       врубання; вбік нічого не тримає — і це має виглядати як удар.

       dy < 0 означає, що центр клітинки нижчий за кірку (вісь y вниз),
       а !sideways — що дотик прийшовся переважно по вертикалі. */
    const gnawing = !broke && !sideways && dy < 0;
    this.hitStrength = Math.max(this.hitStrength, gnawing ? P.crackBounce : 1);
    this.checkDead(p, idx);
  }

  /* Наскільки пружним буде цей удар — суто ГЕОМЕТРІЯ: чим ударили і
     якого зараз розміру кірка. Ігрова частина (що це був за блок,
     вистояв він чи розсипався) домножується окремо — див. hitStrength.

     Кірка не куля. Головка важка — удар нею глухий; ручка легка —
     від неї кірку відкидає сильніше. Рахуємо, наскільки напрямок
     головки збігається з напрямком НА ГРАНЬ, і інтерполюємо між
     headBounce і handleBounce.

     Напрямок головки виводимо з rot: за побудовою при rot = restRot
     вона дивиться ВНИЗ, тобто в бік (0, +1). Кут «вниз» — це PI/2,
     отже зсув між rot і справжнім кутом головки сталий.

     ЗНАК. n дивиться ВІД грані до центра кірки, головка ж під час
     удару дивиться В грань — тому мінус. Без нього виходило рівно
     навпаки: найчастіший удар у грі (кірка висить головкою вниз і
     падає на блок під собою) вважався ударом ручкою й отримував
     handleBounce = 1.3 замість headBounce = 0.62. Кожен звичайний
     дотик відкидав кірку вдвічі сильніше, ніж мав.

     Друга частина — розмір: велика кірка стрибає гірше, бо маса
     росте швидше за силу удару. */
  private hitBounce(p: Pick, nx: number, ny: number): number {
    const head = p.rot - P.restRot + Math.PI / 2;
    // 1 — вдарили ГОЛОВКОЮ, -1 — ручкою
    const align = -(Math.cos(head) * nx + Math.sin(head) * ny);
    const t = (align + 1) / 2;                         // 0 ручка .. 1 головка
    let k = P.handleBounce + (P.headBounce - P.handleBounce) * t;
    if (p.scale > 1) {
      // scale росте степенями CONFIG.grow.scale, тож і гасіння степеневе
      const steps = Math.log(p.scale) / Math.log(CONFIG.grow.scale);
      k *= Math.pow(P.sizeDamp, steps);
    }
    return k;
  }

  private checkDead(p: Pick, idx: number): void {
    if (p.hp <= 0) {
      p.hp = 0;
      p.dead = true;
      this.events.push({ t: 'pickdead', x: p.x, y: p.y, tier: p.tier.id as TierId, pick: idx });
    }
    if (this.hits >= P.maxHits * this.picks.length) this.finish('limit');
  }

  private finish(reason: RunEndReason): void {
    if (this.over) return;
    this.over = true;
    this.reason = reason;
    this.events.push({ t: 'end', reason });
  }
}
