/* ============================================================
   КОНТРАКТИ — типи, які перетинають межу процесу.

   ЧОМУ ОКРЕМИЙ ПАКЕТ. Ті самі форми інакше оголошувались би двічі:
   на сервері й у грі, — і розходились би рівно так, як розходяться
   копії: одну поправили, другу забули.

   Тут лежить ЛИШЕ те, про що сервер і клієнт домовились по дроту.
   Жодної логіки й жодних залежностей: пакет має лишатись описом, який
   можна імпортувати звідусіль, не тягнучи за собою рантайм.
   ============================================================ */

/* ---- щоденна нагорода ----

   Дві речі в одному вікні, бо гравець отримує їх одним дотиком:
     refill — щоденне поповнення коінів, однакове щодня;
     streak — нагорода за серію заходів поспіль, росте з кожним днем
              і скидається, якщо пропустити добу. */

export interface DailyState {
  /** чи можна забрати нагороду просто зараз */
  ready: boolean;
  /* День серії, який гравець ЗАБЕРЕ наступним (1..rewards.length).
     Коли ready=false — день, який він уже забрав сьогодні. */
  day: number;
  /** щоденне поповнення, коінів */
  refill: number;
  /** нагорода серії на кожен день циклу: rewards[0] — перший день */
  rewards: number[];
  /** коли почнеться наступна доба (мс epoch) */
  nextAt: number;
  /* Час СЕРВЕРА на момент відповіді. Таймер «до нової нагороди» — це
     nextAt мінус «зараз», і на збитому годиннику телефону він брехав
     би на години. */
  now: number;
}

/** Що саме лягло на баланс після claim. */
export interface DailyClaim {
  /** день серії, за який нараховано */
  day: number;
  refill: number;
  streak: number;
  /** усе разом — саме це число летить на баланс */
  total: number;
  balance: number;
  state: DailyState;
}
